def main():
    orig_lines = TARGET.read_text(encoding="utf-8").splitlines()
    orig = [json.loads(l) for l in orig_lines if l.strip()]
    orig_ids = [o["anon_id"] for o in orig]
    assert len(ROWS) == 122, f"score rows {len(ROWS)} != 122"
    assert [r[0] for r in ROWS] == orig_ids, "anon_id order/set mismatch vs original package"
    out = []
    for anon_id, d, c, t, reason in ROWS:
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), (anon_id, v)
        total = d + c + t
        out.append({
            "anon_id": anon_id,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        })
    TARGET.write_text("\n".join(json.dumps(o, ensure_ascii=False) for o in out) + "\n", encoding="utf-8")
    # read-back self-verification
    back_lines = TARGET.read_text(encoding="utf-8").splitlines()
    back = [json.loads(l) for l in back_lines if l.strip()]
    assert len(back) == 122, f"written lines {len(back)} != 122"
    assert {o["anon_id"] for o in back} == set(orig_ids), "anon_id set mismatch after write"
    for o in back:
        assert abs(o["total"] - (o["direction"] + o["claims"] + o["timing"])) < 1e-9, o
        assert o["pass"] == (o["total"] >= 4), o
    npass = sum(1 for o in back if o["pass"])
    print(f"OK wrote {len(back)} lines; pass {npass}; fail {len(back)-npass}; mean total {sum(o['total'] for o in back)/len(back):.3f}")

if __name__ == "__main__":
    main()
