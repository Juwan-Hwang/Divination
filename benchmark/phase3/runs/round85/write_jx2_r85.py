anons = [r["anon_id"] for r in rows]
assert set(anons) == set(S.keys()), (set(anons) ^ set(S.keys()))

out_lines = []
for a in anons:
    d, c, t, reason = S[a]
    for v in (d, c, t):
        assert 0 <= v <= 2 and (v * 2) == int(v * 2), (a, v)
    total = d + c + t
    out_lines.append(json.dumps({
        "anon_id": a, "direction": d, "claims": c, "timing": t,
        "total": total, "pass": total >= 4, "reason": reason,
    }, ensure_ascii=False))

OUT.write_text("\n".join(out_lines) + "\n", encoding="utf-8")

