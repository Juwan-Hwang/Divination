for w in written:
    assert w["total"] == w["direction"] + w["claims"] + w["timing"]
    for k in ("direction", "claims", "timing"):
        v = w[k]
        assert 0 <= v <= 2 and (v * 2) == int(v * 2), (w["anon_id"], k, v)
    assert w["pass"] == (w["total"] >= 4)

npass = sum(1 for w in written if w["pass"])
from collections import Counter
dist = Counter(w["total"] for w in written)
