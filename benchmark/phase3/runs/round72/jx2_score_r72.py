def main():
    rows_in = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    anons = [r["anon_id"] for r in rows_in]
    assert len(anons) == 122, len(anons)
    assert set(anons) == set(S.keys()), (set(anons) ^ set(S.keys()))
    out_lines = []
    for a in anons:
        d, c, t, reason = S[a]
        assert d in DOMAIN and c in DOMAIN and t in DOMAIN, a
        total = d + c + t
        rec = {"anon_id": a, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        out_lines.append(json.dumps(rec, ensure_ascii=False))
    # segmented write: 3 segments, verify line count after each
    bounds = [0, 41, 82, 122]
    with open(OUT, "w", encoding="utf-8") as f:
        for s in range(3):
            for line in out_lines[bounds[s]:bounds[s+1]]:
                f.write(line + "\n")
            f.flush(); os.fsync(f.fileno())
            n = sum(1 for _ in open(OUT, encoding="utf-8"))
            assert n == bounds[s+1], (s, n)
    # final verification
    final = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(final) == 122
    assert [r["anon_id"] for r in final] == anons
    for r in final:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    print("OK lines=122 pass=", sum(1 for r in final if r["pass"]))

