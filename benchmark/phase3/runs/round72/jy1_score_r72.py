def main():
    rows = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    mapping = json.loads(MAPPING.read_text(encoding="utf-8"))
    assert len(rows) == 122, len(rows)
    anons = [r["anon_id"] for r in rows]
    assert set(anons) == set(S.keys()), (set(anons) ^ set(S.keys()))
    # claims核验:回读每件 prediction_text 全文(仅断言非空,不改分)
    for a in anons:
        cid = mapping[a]
        pj = json.loads((BASE / "predictions" / f"{cid}.json").read_text(encoding="utf-8"))
        assert pj.get("prediction_text"), (a, cid)
    out = []
    for a in anons:
        d, c, t, reason = S[a]
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, a
        total = d + c + t
        out.append({"anon_id": a, "direction": d, "claims": c, "timing": t,
                    "total": total, "pass": total >= 4, "reason": reason})
    # 分段写入逐段验行数:4段
    segs = [out[i:i+31] for i in range(0, len(out), 31)]
    written = 0
    for i, seg in enumerate(segs):
        mode = "w" if i == 0 else "a"
        with BLOCK.open(mode, encoding="utf-8") as f:
            for r in seg:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        written += len(seg)
        cur = [l for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
        assert len(cur) == written, (i, len(cur), written)
    final = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(final) == 122 and [r["anon_id"] for r in final] == anons
