ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    rows_in = [json.loads(l) for l in TARGET.read_text(encoding="utf-8").splitlines() if l.strip()]
    anon_in = [r["anon_id"] for r in rows_in]
    assert len(anon_in) == 121, f"input lines {len(anon_in)} != 121"
    assert [a for a, *_ in SCORES] == anon_in, "anon order/set mismatch with input block"
    mapping = json.loads(MAPPING.read_text(encoding="utf-8"))
    assert all(a in mapping for a in anon_in), "anon missing in host-mapping"

    out_rows = []
    for anon, d, c, t, reason in SCORES:
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, (anon, d, c, t)
        total = d + c + t
        out_rows.append({
            "anon_id": anon, "direction": d, "claims": c, "timing": t,
            "total": total, "pass": total >= 4, "reason": reason,
        })
    assert len(out_rows) == 121 and len({r["anon_id"] for r in out_rows}) == 121

    # 分段写入: 3 段, 每段写后回读验累计行数
    bounds = [(0, 41), (41, 82), (82, 121)]
    written = 0
    for i, (lo, hi) in enumerate(bounds):
        mode = "w" if i == 0 else "a"
        with TARGET.open(mode, encoding="utf-8") as f:
            for r in out_rows[lo:hi]:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        written = hi
        cur = [l for l in TARGET.read_text(encoding="utf-8").splitlines() if l.strip()]
        assert len(cur) == written, f"segment {i}: lines {len(cur)} != {written}"
        for l in cur:
            rr = json.loads(l)
            assert set(rr) == {"anon_id", "direction", "claims", "timing", "total", "pass", "reason"}
            assert rr["total"] == rr["direction"] + rr["claims"] + rr["timing"]
            assert rr["pass"] == (rr["total"] >= 4)
    final = [json.loads(l) for l in TARGET.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert [r["anon_id"] for r in final] == anon_in
    npass = sum(1 for r in final if r["pass"])
    print(f"OK lines={len(final)} pass={npass} bytes={TARGET.stat().st_size}")

if __name__ == "__main__":
    main()
