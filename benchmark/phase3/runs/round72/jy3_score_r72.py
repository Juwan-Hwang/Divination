ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    with open(BLOCK, encoding="utf-8") as f:
        rows = [json.loads(l) for l in f if l.strip()]
    with open(MAP, encoding="utf-8") as f:
        mapping = json.load(f)
    assert len(rows) == 122, len(rows)
    anons = [r["anon_id"] for r in rows]
    assert set(anons) == set(SCORES.keys()), "anon set mismatch"
    # 回读核验: 每 anon 经 mapping 得 case_id 且 prediction 文件含 prediction_text
    for a in anons:
        cid = mapping[a]
        with open(BASE + "/predictions/" + cid + ".json", encoding="utf-8") as f:
            pred = json.load(f)
        assert pred["prediction_text"], a
    out_lines = []
    for a in anons:
        d, c, t, reason = SCORES[a]
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, a
        total = d + c + t
        rec = {"anon_id": a, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        out_lines.append(json.dumps(rec, ensure_ascii=False))
    assert len(out_lines) == 122
    # 分段写入,逐段验行数
    segments = [out_lines[0:31], out_lines[31:62], out_lines[62:92], out_lines[92:122]]
    written = 0
    with open(BLOCK, "w", encoding="utf-8") as f:
        for seg in segments:
            for line in seg:
                f.write(line + "\n")
            f.flush()
            written += len(seg)
            with open(BLOCK, encoding="utf-8") as rf:
                n = sum(1 for _ in rf)
            assert n == written, (n, written)
    # 终验
    with open(BLOCK, encoding="utf-8") as f:
        final = [json.loads(l) for l in f if l.strip()]
    assert len(final) == 122
    assert [r["anon_id"] for r in final] == anons
    for r in final:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    npass = sum(1 for r in final if r["pass"])
    print("rows=122 pass=%d" % npass)

if __name__ == "__main__":
    main()
