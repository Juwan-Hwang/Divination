def main():
    rows = [json.loads(l) for l in open(BLOCK, encoding='utf-8')]
    assert len(rows) == 121, len(rows)
    assert all('outcome_record' in r for r in rows), 'input already overwritten?'
    anon_in = [r['anon_id'] for r in rows]
    assert set(anon_in) == set(S), (set(anon_in) ^ set(S))
    out = []
    for a in anon_in:
        d, c, t, reason = S[a]
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, a
        total = d + c + t
        out.append({'anon_id': a, 'direction': d, 'claims': c, 'timing': t,
                    'total': total, 'pass': total >= 4, 'reason': reason})
    # segmented write + per-segment assertions
    segs = [out[i:i+31] for i in range(0, 121, 31)]
    with open(BLOCK, 'w', encoding='utf-8') as f:
        done = []
        for seg in segs:
            for o in seg:
                f.write(json.dumps(o, ensure_ascii=False) + '\n')
            f.flush()
            done += seg
            assert len(done) <= 121
            for o in done:
                assert o['total'] == o['direction'] + o['claims'] + o['timing']
                assert o['pass'] == (o['total'] >= 4)
    chk = [json.loads(l) for l in open(BLOCK, encoding='utf-8')]
    assert len(chk) == 121 and [r['anon_id'] for r in chk] == anon_in
    print('rows', len(chk), 'pass', sum(r['pass'] for r in chk))

if __name__ == '__main__':
    main()
