def digest():
    rows,mapping=load_block()
    out=[]
    for r in rows:
        anon=r["anon_id"]; cid=mapping[anon]
        p=json.load(open(os.path.join(PRED,cid+".json"),encoding="utf-8"))
        ptext=p.get("prediction_text","")
        out.append({"anon_id":anon,"case_id":cid,"prediction_text":ptext,"outcome_record":r.get("outcome_record",""),
                    "carry_note":r.get("carry_note"),"editor_note":r.get("editor_note")})
    with open(os.path.join(BASE,"jx3_digest.json"),"w",encoding="utf-8") as f:
        json.dump(out,f,ensure_ascii=False,indent=1)
    print(len(out))

