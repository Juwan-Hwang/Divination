def write_scores():
    rows,mapping=load_block()
    anons=[r["anon_id"] for r in rows]
    assert set(SCORES.keys())==set(anons), f"mismatch missing={set(anons)-set(SCORES)} extra={set(SCORES)-set(anons)}"
    assert len(anons)==122
    allowed={0,0.5,1,1.5,2}
    lines=[]
    for anon in anons:
        d,c,t,reason=SCORES[anon]
        assert d in allowed and c in allowed and t in allowed, anon
        total=d+c+t
        lines.append(json.dumps({"anon_id":anon,"direction":d,"claims":c,"timing":t,"total":total,"pass":total>=4,"reason":reason},ensure_ascii=False))
    with open(JUDGE,"w",encoding="utf-8") as f:
        f.write("\n".join(lines)+"\n")
    # re-read assertions
    back=[json.loads(l) for l in open(JUDGE,encoding="utf-8") if l.strip()]
    assert len(back)==122 and [b["anon_id"] for b in back]==anons
    for b in back:
        assert b["total"]==b["direction"]+b["claims"]+b["timing"]
        assert b["pass"]==(b["total"]>=4)
    print("rows",len(back),"pass",sum(1 for b in back if b["pass"]))

