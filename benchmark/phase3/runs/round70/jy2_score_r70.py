ALLOWED = {0,0.5,1,1.5,2}
def main():
    rows = [json.loads(l) for l in INOUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows) == 122, len(rows)
    assert len(S) == 122, len(S)
    mp = json.loads(MAP.read_text(encoding="utf-8"))
    anons = [r["anon_id"] for r in rows]
    assert set(anons) == set(mp.keys()) & set(anons)  # anon subset of mapping
    # claims回读原文: verify every case file exists & has prediction_text
    for a in anons:
        p = json.loads((BASE/"predictions"/f"{mp[a]}.json").read_text(encoding="utf-8"))
        assert p.get("prediction_text"), a
    out = []
    for r,(d,c,t,reason) in zip(rows,S):
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED
        total = d+c+t
        out.append({"anon_id":r["anon_id"],"direction":d,"claims":c,"timing":t,
                    "total":total,"pass":total>=4,"reason":reason})
    # segmented write + per-segment assertions
    segs = [out[i:i+31] for i in range(0,122,31)]
    written = []
    with INOUT.open("w",encoding="utf-8") as f:
        for si,seg in enumerate(segs):
            for o in seg:
                f.write(json.dumps(o,ensure_ascii=False)+"\n")
            f.flush()
            written += seg
            assert len(written) == sum(len(s) for s in segs[:si+1])
            assert {o["anon_id"] for o in written} == set(anons[:len(written)])
            for o in written:
                assert o["total"] == o["direction"]+o["claims"]+o["timing"]
                assert o["pass"] == (o["total"]>=4)
    # final assertions on disk
    back = [json.loads(l) for l in INOUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(back)==122 and {o["anon_id"] for o in back}==set(anons)
    print("rows",len(back),"pass",sum(o["pass"] for o in back))
if __name__=="__main__":
    main()
