def main():
    assert len(S) == 122, len(S)
    input_anons = []
    for line in OUT.read_text(encoding='utf-8').splitlines():
        if line.strip():
            input_anons.append(json.loads(line)['anon_id'])
    assert len(input_anons) == 122, len(input_anons)
    rows = []
    for anon, (d, c, t, reason) in zip(input_anons, S):
        total = d + c + t
        rows.append({'anon_id': anon, 'direction': d, 'claims': c, 'timing': t,
                     'total': total, 'pass': total >= 4, 'reason': reason})
    seg = 31
    written = []
    with OUT.open('w', encoding='utf-8') as f:
        for start in range(0, len(rows), seg):
            chunk = rows[start:start + seg]
            for r in chunk:
                assert r['direction'] in ALLOWED and r['claims'] in ALLOWED and r['timing'] in ALLOWED, r
                assert r['total'] == r['direction'] + r['claims'] + r['timing'], r
                assert r['pass'] == (r['total'] >= 4), r
                f.write(json.dumps(r, ensure_ascii=False) + '\n')
                written.append(r['anon_id'])
            f.flush()
            assert written == input_anons[:len(written)], start
    lines = OUT.read_text(encoding='utf-8').splitlines()
    assert len(lines) == 122, len(lines)
    got = [json.loads(l)['anon_id'] for l in lines]
    assert set(got) == set(input_anons) and len(set(got)) == 122
    print('OK rows=122 pass=', sum(1 for l in lines if json.loads(l)['pass']))


if __name__ == '__main__':
    main()
