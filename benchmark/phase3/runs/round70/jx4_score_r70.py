rows = [json.loads(l) for l in INP.read_text(encoding='utf-8').strip().splitlines()]
assert len(rows) == 121, len(rows)
assert [r['anon_id'] for r in rows] == [s[0] for s in S], 'anon order/set mismatch'
assert len(S) == 121
out_lines = []
SEG = 31
for seg_start in range(0, 121, SEG):
    seg = S[seg_start:seg_start+SEG]
    for anon, d, c, t, reason in seg:
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, anon
        total = d + c + t
        out_lines.append(json.dumps({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                                     "total": total, "pass": total >= 4, "reason": reason}, ensure_ascii=False))
    # segmented flush with assertions on the segment just built
    assert len(out_lines) == min(seg_start + SEG, 121)
    INP.write_text("\n".join(out_lines) + "\n", encoding='utf-8')
final = [json.loads(l) for l in INP.read_text(encoding='utf-8').strip().splitlines()]
assert len(final) == 121
assert {r['anon_id'] for r in final} == {r['anon_id'] for r in rows}
for r in final:
    assert r['total'] == r['direction'] + r['claims'] + r['timing']
    assert r['pass'] == (r['total'] >= 4)
print('rows', len(final), 'pass', sum(1 for r in final if r['pass']))
