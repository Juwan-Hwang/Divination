def main():
    orig_lines = TARGET.read_text(encoding="utf-8").splitlines()
    orig = [json.loads(l) for l in orig_lines if l.strip()]
    assert len(orig) == 121, f"orig lines {len(orig)}"
    assert len(SCORES) == 121, f"scores {len(SCORES)}"
    out = []
    for row, (d, c, t, reason) in zip(orig, SCORES):
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), v
        total = d + c + t
        out.append({
            "anon_id": row["anon_id"],
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        })
    assert [o["anon_id"] for o in out] == [r["anon_id"] for r in orig], "order/anon mismatch"
    assert {o["anon_id"] for o in out} == {r["anon_id"] for r in orig}, "anon set mismatch"
    TARGET.write_text("\n".join(json.dumps(o, ensure_ascii=False) for o in out) + "\n", encoding="utf-8")
    print(f"wrote {len(out)} lines, pass={sum(1 for o in out if o['pass'])}")

if __name__ == "__main__":
    main()
