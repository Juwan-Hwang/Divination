def main():
    with open(IN_PATH, encoding="utf-8") as f:
        block = [json.loads(line) for line in f if line.strip()]
    assert len(block) == 122, f"input lines {len(block)} != 122"
    assert len(SCORES) == 122, f"scores {len(SCORES)} != 122"
    anons = [r["anon_id"] for r in block]

    rows = []
    for anon, (d, c, t, reason) in zip(anons, SCORES):
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, anon
        total = d + c + t
        rows.append({
            "anon_id": anon, "direction": d, "claims": c, "timing": t,
            "total": total, "pass": total >= 4, "reason": reason,
        })

    seg = 31
    written = 0
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        for start in range(0, 122, seg):
            chunk = rows[start:start + seg]
            for r in chunk:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
            f.flush()
            written += len(chunk)
            with open(OUT_PATH, encoding="utf-8") as g:
                back = [json.loads(line) for line in g if line.strip()]
            assert len(back) == written, f"seg@{start}: {len(back)} != {written}"
            for i, r in enumerate(back):
                assert r["anon_id"] == anons[i], f"order mismatch at {i}"
                assert r["direction"] in ALLOWED and r["claims"] in ALLOWED and r["timing"] in ALLOWED
                assert r["total"] == r["direction"] + r["claims"] + r["timing"]
                assert r["pass"] == (r["total"] >= 4)
    npass = sum(1 for r in rows if r["pass"])
    print(f"OK rows=122 pass={npass}")

if __name__ == "__main__":
    main()
