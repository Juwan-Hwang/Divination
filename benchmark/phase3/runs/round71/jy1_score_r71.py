ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    with open(IN_PATH, encoding="utf-8") as f:
        rows = [json.loads(line) for line in f if line.strip()]
    assert len(rows) == 122, f"input rows={len(rows)}"
    assert len(SCORES) == 122, f"scores={len(SCORES)}"
    anons = [r["anon_id"] for r in rows]

    out_lines = []
    seg = 31  # write in segments
    for start in range(0, 122, seg):
        end = min(start + seg, 122)
        chunk = []
        for i in range(start, end):
            d, c, t, reason = SCORES[i]
            assert d in ALLOWED and c in ALLOWED and t in ALLOWED, (i, d, c, t)
            total = d + c + t
            rec = {
                "anon_id": anons[i],
                "direction": d,
                "claims": c,
                "timing": t,
                "total": total,
                "pass": total >= 4,
                "reason": reason,
            }
            assert rec["total"] == d + c + t
            assert rec["pass"] == (total >= 4)
            chunk.append(json.dumps(rec, ensure_ascii=False))
        assert chunk, start
        out_lines.extend(chunk)
        print(f"segment {start}-{end-1} ok ({len(chunk)} lines)")

    assert len(out_lines) == 122
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines) + "\n")

    # re-read and verify order position-wise
    with open(OUT_PATH, encoding="utf-8") as f:
        written = [json.loads(line) for line in f if line.strip()]
    assert len(written) == 122
    assert [w["anon_id"] for w in written] == anons, "anon order mismatch"
    npass = sum(1 for w in written if w["pass"])
    print(f"written 122 lines, pass={npass}")

if __name__ == "__main__":
    main()
