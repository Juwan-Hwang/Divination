def main():
    packet = json.loads((BASE / "judging" / "packet3.json").read_text())
    assert len(packet) == 122, len(packet)
    assert len(S) == 122, len(S)
    packet_anons = [p["anon_id"] for p in packet]
    rows = []
    for item, (d, c, t, reason) in zip(packet, S):
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), (item["anon_id"], v)
        total = d + c + t
        rows.append({"anon_id": item["anon_id"], "direction": d, "claims": c,
                     "timing": t, "total": total, "pass": total >= 4, "reason": reason})
    assert len(rows) == 122
    assert {r["anon_id"] for r in rows} == set(packet_anons)
    assert [r["anon_id"] for r in rows] == packet_anons
    for r in rows:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    out = BASE / "judging" / "judgeX-block3.jsonl"
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n")
    print("rows", len(rows), "pass", sum(1 for r in rows if r["pass"]))

if __name__ == "__main__":
    main()
