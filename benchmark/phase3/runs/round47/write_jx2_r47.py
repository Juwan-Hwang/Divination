def main():
    packet = json.loads(PACKET.read_text(encoding="utf-8"))
    assert len(packet) == 122, f"packet rows {len(packet)} != 122"
    assert len(ROWS) == 122, f"score rows {len(ROWS)} != 122"
    packet_anons = [r["anon_id"] for r in packet]
    score_anons = [r[0] for r in ROWS]
    assert set(score_anons) == set(packet_anons), "anon set mismatch vs packet2"
    assert len(set(score_anons)) == 122, "duplicate anon in scores"
    assert score_anons == packet_anons, "anon order mismatch vs packet2"
    lines = []
    for anon, d, c, t, reason in ROWS:
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), f"{anon} score off-scale {v}"
        total = d + c + t
        lines.append(json.dumps({
            "anon_id": anon, "direction": d, "claims": c, "timing": t,
            "total": total, "pass": total >= 4, "reason": reason,
        }, ensure_ascii=False))
    # verify totals/pass before writing
    for line in lines:
        o = json.loads(line)
        assert o["total"] == o["direction"] + o["claims"] + o["timing"]
        assert o["pass"] == (o["total"] >= 4)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    npass = sum(1 for line in lines if json.loads(line)["pass"])
    print(f"wrote {len(lines)} rows, pass={npass} -> {OUT}")

if __name__ == "__main__":
    main()
