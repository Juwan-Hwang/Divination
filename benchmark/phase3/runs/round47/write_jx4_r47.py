missing = [a for a in anons if a not in S]
assert not missing, missing

rows = []
for a in anons:
    d, c, t, reason = S[a]
    for v in (d, c, t):
        assert 0 <= v <= 2 and (v * 2) == int(v * 2), (a, v)
    total = d + c + t
    rows.append({"anon_id": a, "direction": d, "claims": c, "timing": t,
                 "total": total, "pass": total >= 4, "reason": reason})

assert len(rows) == 121
assert {r['anon_id'] for r in rows} == set(anons)
for r in rows:
    assert r['total'] == r['direction'] + r['claims'] + r['timing']
    assert r['pass'] == (r['total'] >= 4)

with open(OUT, 'w', encoding='utf-8') as f:
    for r in rows:
        f.write(json.dumps(r, ensure_ascii=False) + '\n')
print('written', OUT, 'rows', len(rows), 'pass', sum(r['pass'] for r in rows))
