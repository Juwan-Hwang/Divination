def main():
    packet = json.loads(PACKET.read_text(encoding="utf-8"))
    assert len(packet) == 28, len(packet)
    anon_ids = [x["anon_id"] for x in packet]
    assert set(anon_ids) == set(SCORES.keys()), (set(anon_ids) ^ set(SCORES.keys()))
    lines = []
    for anon in anon_ids:
        d, c, t, reason = SCORES[anon]
        for v in (d, c, t):
            assert 0.0 <= v <= 2.0 and (v * 2) == int(v * 2), (anon, v)
        total = d + c + t
        row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        assert row["total"] == row["direction"] + row["claims"] + row["timing"]
        assert row["pass"] == (row["total"] >= 4)
        lines.append(json.dumps(row, ensure_ascii=False))
    assert len(lines) == 28
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # read-back verification
    rows = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows) == 28
    for r in rows:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    n = len(rows)
    print("rows", n)
    print("direction_mean", sum(r["direction"] for r in rows) / n)
    print("claims_mean", sum(r["claims"] for r in rows) / n)
    print("timing_mean", sum(r["timing"] for r in rows) / n)
    print("total_mean", sum(r["total"] for r in rows) / n)
    print("pass_count", sum(1 for r in rows if r["pass"]))

if __name__ == "__main__":
    main()
