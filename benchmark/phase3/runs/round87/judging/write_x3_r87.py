def main():
    rows = [json.loads(l) for l in open(IN, encoding='utf-8')]
    assert len(rows) == 122, len(rows)
    assert len(S) == 122, len(S)
    out = []
    for r, (d, c, t, reason) in zip(rows, S):
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), v
        total = d + c + t
        rec = {"anon_id": r["anon_id"], "direction": d, "claims": c,
               "timing": t, "total": total, "pass": total >= 4, "reason": reason}
        assert rec["total"] == rec["direction"] + rec["claims"] + rec["timing"]
        assert rec["pass"] == (rec["total"] >= 4)
        out.append(rec)
    with open(OUT, 'w', encoding='utf-8') as f:
        for rec in out:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    n = len(out)
    print("n", n)
    print("direction_mean", sum(o["direction"] for o in out) / n)
