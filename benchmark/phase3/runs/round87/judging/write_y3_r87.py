def main():
    rows = [json.loads(l) for l in IN.read_text().splitlines() if l.strip()]
    assert len(rows) == 122, len(rows)
    assert len(S) == 122, len(S)
    out = []
    for r, (d, c, t, reason) in zip(rows, S):
        total = d + c + t
        p = total >= 4
        rec = {"anon_id": r["anon_id"], "direction": d, "claims": c,
               "timing": t, "total": total, "pass": p, "reason": reason}
        assert rec["total"] == rec["direction"] + rec["claims"] + rec["timing"]
        assert rec["pass"] == (rec["total"] >= 4)
        out.append(rec)
    with OUT.open("w") as f:
        for rec in out:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    n = len(out)
    print("rows", n)
    print("direction_mean", sum(r["direction"] for r in out) / n)
    print("claims_mean", sum(r["claims"] for r in out) / n)
    print("timing_mean", sum(r["timing"] for r in out) / n)
    print("total_mean", sum(r["total"] for r in out) / n)
    print("pass", sum(1 for r in out if r["pass"]))

if __name__ == "__main__":
    main()
