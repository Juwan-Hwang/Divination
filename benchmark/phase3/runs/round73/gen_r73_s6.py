def parse_lines(raw_lines):
    lines = []
    n = len(raw_lines)
    for i, s in enumerate(raw_lines):
        pos = n - i  # top is highest
        ms = re.findall(QIN_RE, s)
        if not ms: continue
        oq, oz, owx = ms[0]
        ch = ms[1] if len(ms) > 1 else None
        seg = s.split("　")[0]
        lines.append({"pos": pos, "qin": oq, "zhi": oz, "wx": owx,
                      "changed": ch, "shi": "世" in seg, "ying": "應" in seg})
    return lines

