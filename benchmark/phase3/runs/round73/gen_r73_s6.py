def rel(a, b):
    """a 五行 -> b 五行 relation"""
    if a == b: return "比和"
    if SHENG[a] == b: return "生"
    if KE[a] == b: return "克"
    if SHENG[b] == a: return "被生"
    if KE[b] == a: return "被克"
    return "?"

def month_score(mwx, uwx):
    if mwx == uwx: return 2.0, "臨月建一系（旺）"
    if SHENG[mwx] == uwx: return 1.5, "月建生用神（相）"
