def mp_predict(cid, d):
    ctx = d.get("context", {}); q = ctx.get("question", "")
    pred, extra = MPMAP[cid]
    conf = float(re.search(r"置信 (0\.\d+)", pred).group(1))
    first = f"卡面未標註 tradition 字段，按題面體裁自決（本例：{q}）"
    basis = (f"{first}\n本例標示：{cid}｜問「{q}」｜問時 {ctx.get('asked_at','')}｜對象 {json.dumps(d.get('subject',{}), ensure_ascii=False)}。\n"
             f"已載面表：主問面已斷；題面已載的選情/民調/連署/人選諸面逐面處置見斷語與下行；餘面題面未載。題面錨點核：人名與日期為事實錨點直讀，無轉應可取，已列此行。\n"
             f"輸入殘損（重要）：本例卡面未載任何卦盤、命盤、牌面或起占數據，无從按六爻/八字/塔羅任一盤面作斷；依凍結提示不臆補盤面，只按題面已載事實（事實優先序）與選舉格局作情景判斷，置信已降至{conf}。{extra}\n"
             f"斷項過閘：每條斷項指代鏈回題面已載面、觸發為題面事實面本身；無盤面觸發可指認之細節（精確票數/席次）已按粒度收束降為量級帶或刪去。R61-REV1：應期座標為題面既定投票日，非盤面推得，二路復推不適用（無盤面路徑可換），已在此明寫；方向鎖定不變。")
    return {"case_id": cid, "prediction_text": pred, "basis": basis, "confidence": conf,
            "trigger": {"changed_main": False, "reserve_used": False, "disputed": False, "reason": ""}}

def main():
    total = 0
    for bname, ids in BATCHES.items():
        written = []
        for cid in ids:
            d = json.loads((BASE / f"{cid}.json").read_text())
            assert (d.get("id") or d.get("uid")) == cid, cid
            if cid.startswith("LY-"): rec = ly_predict(cid, d)
            elif cid.startswith("MH-"): rec = mh_predict(cid, d)
            else: rec = mp_predict(cid, d)
            assert rec["case_id"] == cid
            assert set(rec.keys()) == {"case_id","prediction_text","basis","confidence","trigger"}
            assert set(rec["trigger"].keys()) == {"changed_main","reserve_used","disputed","reason"}
            (OUT / f"{cid}.json").write_text(json.dumps(rec, ensure_ascii=False, indent=1))
            written.append(cid)
        assert written == ids, (bname, written)
        assert len(written) == 20, bname
        total += len(written)
        print(bname, "written", len(written))
    assert total == 60
    print("TOTAL", total)

if __name__ == "__main__":
    main()
