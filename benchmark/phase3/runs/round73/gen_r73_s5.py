def parse_token(tok):
    m = LINE_RE.search(tok)
    if not m: return None
    rel, br, el = m.groups()
    return {'rel':rel,'br':br,'el':el,'moving':('ㄨ' in tok or '○' in tok or 'ㄨ' in tok),
            'shi':'世' in tok,'ying':'應' in tok,'old_yin':('ㄨ' in tok),'old_yang':('○' in tok)}

