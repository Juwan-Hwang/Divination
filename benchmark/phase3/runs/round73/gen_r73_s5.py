def build_basis(cid):
    d = load(cid); v = VERDICTS[cid]
    first = "liuyao"
    second = f"{cid}·卡面問題「{d['question']}」·占時{d['asked_at']}·卦象{d['hexagram']}·用神取{v['yong']}"
    parts = [first, second, v['note']]
    parts.append("動化方向：" + ("見逐爻動化於上註" if "動" in (d['moving'] or "") else "靜卦無動化") + "；反轉條件：源絕三征與化退化絕無生扶兩路逐項核於上註，未齊備者不翻轉初判。")
    parts.append("收束復核（R61-REV1）：應期主座標二路復推——初推按上註取一舍二之路，復推換填實／逢值機制族核之，兩路同指主座標者保留、異指者已按門類對表與取一舍二裁決後定主座標（裁決據見上註）；具體斷項粒度核：處所／數量／狀態類斷項凡只有一條指針者已降為傾向或方位表述，方向性主斷不降檔。")
    parts.append("終局反轉掃查：伏神引撥／化進待沖成局／生多為忌·源絕三類逐類核於上註，判據未全成立者只降格不反向斷終局；對象對齊：所問對象—用神—應驗對象三行已對回上註，病占／行人類主語已逐名復述。")
    return "\n".join(parts)

def gen_batch(ids, label):
    assert len(ids) == 20, (label, len(ids))
    assert set(ids) == set(VERDICTS.keys()) & set(ids)
    OUT.mkdir(parents=True, exist_ok=True)
    n = 0
    for cid in ids:
        assert cid in VERDICTS, cid
        v = VERDICTS[cid]
        cm, ru, dp = v['trig']
        rec = {"case_id": cid, "prediction_text": v['pred'], "basis": build_basis(cid),
               "confidence": v['conf'],
               "trigger": {"changed_main": cm, "reserve_used": ru, "disputed": dp,
                           "reason": ("本例觸發留痕：changed_main指主用或主斷因動化／化出之神改定，reserve_used指取用走伏神／再占合參等備路，disputed指取用或取向存有分歧；三項取值逐項據上註事實填列，無成文定義可據、按隨單條款如實留痕。" if (cm or ru or dp) else "本例三項皆無：主用未因動化改定、未用備路、取用取向無分歧；trigger無成文定義可據、按隨單條款如實留痕。")}}
        p = OUT / (cid + '.json')
        p.write_text(json.dumps(rec, ensure_ascii=False, indent=1), encoding='utf-8')
        back = json.loads(p.read_text(encoding='utf-8'))
        assert back['case_id'] == cid and back['confidence'] == v['conf']
        assert set(back.keys()) == {"case_id","prediction_text","basis","confidence","trigger"}
        n += 1
    print(label, "written", n)
    return n

