def month_state(el, mon):
    if mon is None: return '?'
    me = EL[mon]
    if el==me: return '旺'
    if SHENG[me]==el: return '相'
    if SHENG[el]==me: return '休'
    if KE[el]==me: return '囚'
    return '死'  # month ke el

def day_rel(el, br, day):
    if day is None: return ''
    de = EL[day]; out=[]
    if br==day: out.append('臨日')
    if chong(br,day): out.append('日沖')
    if he(br,day): out.append('日合')
    if SHENG[de]==el: out.append('日生')
    if KE[de]==el: out.append('日克')
    if SHENG[el]==de: out.append('生日泄')
    if KE[el]==de: out.append('克日')
    return '/'.join(out)

def describe(data, cast_idx=0):
    cast = data['casts'][cast_idx] if data['casts'] else []
    lines=[]
    for i,e in enumerate(cast):
        pos = 6-i; t=e['ben']
        s = f"{pos}爻{t['rel']}{t['br']}{t['el']}"
        if t['shi']: s+='世'
        if t['ying']: s+='應'
        if t['moving']: s+='動'
        s += f" 月{month_state(t['el'],data['mon'])} {day_rel(t['el'],t['br'],data['day'])}"
        if data['kong'] and t['br'] in data['kong']: s+=' 空'
        if data['mon'] and chong(t['br'],data['mon']): s+=' 月破'
        if e['bian']:
            b=e['bian']; s += f" 化{b['rel']}{b['br']}{b['el']}(月{month_state(b['el'],data['mon'])})"
            if data['kong'] and b['br'] in data['kong']: s+='化空'
        lines.append(s)
    return lines

