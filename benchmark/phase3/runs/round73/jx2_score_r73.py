def main():
    rows = [json.loads(l) for l in open(BLOCK, encoding="utf-8") if l.strip()]
    in_ids = [r["anon_id"] for r in rows]
    assert len(in_ids) == 122, len(in_ids)
    assert [s[0] for s in SCORES] == in_ids, "anon order/set mismatch"
    out = []
    for anon, d, c, t, reason in SCORES:
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), (anon, v)
        total = d + c + t
        out.append({"anon_id": anon, "direction": d, "claims": c,
                    "timing": t, "total": total, "pass": total >= 4,
                    "reason": reason})
    # segmented write-back with per-segment line-count verification
    segs = [out[:41], out[41:82], out[82:]]
    written = 0
    with open(BLOCK, "w", encoding="utf-8") as f:
        for seg in segs:
            for o in seg:
                f.write(json.dumps(o, ensure_ascii=False) + "\n")
            f.flush()
            written += len(seg)
            cur = sum(1 for l in open(BLOCK, encoding="utf-8") if l.strip())
            assert cur == written, (cur, written)
    chk = [json.loads(l) for l in open(BLOCK, encoding="utf-8") if l.strip()]
    assert len(chk) == 122
    assert [r["anon_id"] for r in chk] == in_ids
    for r in chk:
        assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
        assert r["pass"] == (r["total"] >= 4)
    print("rows", len(chk), "pass", sum(1 for r in chk if r["pass"]))

if __name__ == "__main__":
    main()
