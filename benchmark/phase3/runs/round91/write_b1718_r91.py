def write_batch(batch, tag):
    for p in batch:
        assert set(p.keys()) == {"case_id","prediction_text","basis","confidence","trigger"}, p["case_id"]
        assert 0.0 <= p["confidence"] <= 1.0, p["case_id"]
        assert set(p["trigger"].keys()) == {"changed_main","reserve_used","disputed","reason"}
        path = os.path.join(OUT, p["case_id"] + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(p, f, ensure_ascii=False, indent=1)
    # verify read-back
    for p in batch:
        path = os.path.join(OUT, p["case_id"] + ".json")
        with open(path, encoding="utf-8") as f:
            q = json.load(f)
        assert q["case_id"] == p["case_id"] and q["prediction_text"] and q["basis"]
        assert 0.0 <= q["confidence"] <= 1.0
    print(tag, "written+verified:", len(batch))

