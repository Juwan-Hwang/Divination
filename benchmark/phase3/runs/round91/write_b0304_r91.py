def write_batch(ids, label):
    for cid in ids:
        d = P[cid]
        rec = {"case_id": cid, "prediction_text": d["prediction_text"], "basis": d["basis"],
               "confidence": d["confidence"], "trigger": d["trigger"]}
        (OUT / f"{cid}.json").write_text(json.dumps(rec, ensure_ascii=False, indent=1), encoding="utf-8")
    # per-batch assert: exact-id readback
    for cid in ids:
        rec = json.loads((OUT / f"{cid}.json").read_text(encoding="utf-8"))
        assert rec["case_id"] == cid, cid
        for k in ("prediction_text","basis","confidence","trigger"):
            assert k in rec and rec[k] not in (None,""), (cid,k)
        assert 0.0 <= rec["confidence"] <= 1.0, cid
        tr = rec["trigger"]
        for b in ("changed_main","reserve_used","disputed"):
            assert isinstance(tr[b], bool), (cid,b)
        assert isinstance(tr["reason"], str), cid
    print(f"{label}: wrote+verified {len(ids)}")

