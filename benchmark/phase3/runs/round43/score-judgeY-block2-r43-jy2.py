assert orig_ids == score_ids, "order/set mismatch with original block"
assert len(orig_ids) == len(set(orig_ids)) == len(SCORES)

lines = []
for anon, d, c, t, reason in SCORES:
    total = d + c + t
    lines.append(json.dumps({
        "anon_id": anon, "direction": d, "claims": c, "timing": t,
        "total": total, "pass": total >= 4, "reason": reason,
    }, ensure_ascii=False))
TARGET.write_text("\n".join(lines) + "\n")

# self-verify by re-reading
back = [json.loads(l) for l in TARGET.read_text().splitlines() if l.strip()]
assert len(back) == len(orig), "line count changed"
assert [r["anon_id"] for r in back] == orig_ids, "anon_id set/order changed"
for r in back:
    assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9, r
    assert r["pass"] == (r["total"] >= 4), r
    for k in ("direction", "claims", "timing"):
        v = r[k]
        assert 0 <= v <= 2 and abs(v * 2 - round(v * 2)) < 1e-9, r
print(f"OK rows={len(back)} pass={sum(1 for r in back if r['pass'])} fail={sum(1 for r in back if not r['pass'])}")
