def main():
    rows = [json.loads(l) for l in BLOCK.read_text().splitlines() if l.strip()]
    assert len(rows) == 121, len(rows)
    assert len(S) == 121, len(S)
    out = []
    for row, (d, c, t, reason) in zip(rows, S):
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), v
        total = d + c + t
        out.append({"anon_id": row["anon_id"], "direction": d, "claims": c,
                    "timing": t, "total": total, "pass": total >= 4, "reason": reason})
    # assertions: anon set equality with original block, totals, pass rule
    assert {o["anon_id"] for o in out} == {r["anon_id"] for r in rows}
    for o in out:
        assert o["total"] == o["direction"] + o["claims"] + o["timing"]
        assert o["pass"] == (o["total"] >= 4)
    BLOCK.write_text("\n".join(json.dumps(o, ensure_ascii=False) for o in out) + "\n")
    print("rows", len(out), "pass", sum(o["pass"] for o in out), "bytes", BLOCK.stat().st_size)

if __name__ == "__main__":
    main()
