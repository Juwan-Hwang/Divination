def main():
    orig = [json.loads(l) for l in TARGET.read_text(encoding="utf-8").splitlines() if l.strip()]
    orig_anons = [r["anon_id"] for r in orig]
    assert len(orig_anons) == 122, f"原块行数 {len(orig_anons)} != 122"
    assert len(ROWS) == 122, f"评分行数 {len(ROWS)} != 122"
    assert [r[0] for r in ROWS] == orig_anons, "anon 顺序/集合与原块不一致"
    assert len(set(orig_anons)) == 122
    out_lines = []
    for anon, d, c, t, reason in ROWS:
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), f"{anon} 分值非法 {v}"
        total = d + c + t
        row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        assert row["total"] == row["direction"] + row["claims"] + row["timing"]
        assert row["pass"] == (row["total"] >= 4)
        out_lines.append(json.dumps(row, ensure_ascii=False))
    TARGET.write_text("\n".join(out_lines) + "\n", encoding="utf-8")
    # 覆写后复验
    chk = [json.loads(l) for l in TARGET.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(chk) == 122
    assert {r["anon_id"] for r in chk} == set(orig_anons)
    for r in chk:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    npass = sum(1 for r in chk if r["pass"])
    print(f"rows=122 pass={npass} bytes={TARGET.stat().st_size}")

