SEGMENTS = [SEG1, SEG2, SEG3, SEG4]

def main():
    block_ids = []
    with open(BLOCK, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                block_ids.append(json.loads(line)["anon_id"])
    all_rows = [r for seg in SEGMENTS for r in seg]
    assert len(all_rows) == len(block_ids) == 122, (len(all_rows), len(block_ids))
    assert [r[0] for r in all_rows] == block_ids, "anon_id 顺序与块文件不一致"
    if os.path.exists(OUT):
        os.remove(OUT)
    written = 0
    for i, seg in enumerate(SEGMENTS, 1):
        with open(OUT, "a", encoding="utf-8") as f:
            for anon, d, c, t, reason in seg:
                assert d in [x/2 for x in range(5)] and c in [x/2 for x in range(5)] and t in [x/2 for x in range(5)]
                total = d + c + t
                rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
                written += 1
        # 逐段断言：回读行数
        n = sum(1 for _ in open(OUT, encoding="utf-8"))
        assert n == written, (i, n, written)
        print(f"segment {i} ok, cumulative {n}")
    # 写后自验
    rows = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(rows) == len(block_ids) == 122
    assert [r["anon_id"] for r in rows] == block_ids
    for r in rows:
        assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
        assert r["pass"] == (r["total"] >= 4)
    from collections import Counter
    print("total lines:", len(rows))
    print("pass:", sum(1 for r in rows if r["pass"]), "fail:", sum(1 for r in rows if not r["pass"]))
    print("total dist:", dict(sorted(Counter(r["total"] for r in rows).items())))
    print("bytes:", os.path.getsize(OUT))

if __name__ == "__main__":
    main()
