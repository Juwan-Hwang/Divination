def main():
    block_ids = [json.loads(l)["anon_id"] for l in open(BLOCK, encoding="utf-8") if l.strip()]
    assert len(block_ids) == 122, len(block_ids)
    ids = [s[0] for s in S]
    assert ids == block_ids, "order/id mismatch vs block"
    lines = []
    for anon, d, c, t, reason in S:
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), (anon, v)
        total = d + c + t
        row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        lines.append(json.dumps(row, ensure_ascii=False))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    # read-back verification
    back = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(back) == len(block_ids) == 122
    for r in back:
        assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
        assert r["pass"] == (r["total"] >= 4)
    from collections import Counter
    dist = Counter(r["total"] for r in back)
    npass = sum(1 for r in back if r["pass"])
    print("written", len(back), "pass", npass, "fail", len(back) - npass)
    print("dist", dict(sorted(dist.items())))

if __name__ == "__main__":
    main()
