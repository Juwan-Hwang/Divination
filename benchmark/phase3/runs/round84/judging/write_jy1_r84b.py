SEGS = [SEG1, SEG2, SEG3, SEG4]

def emit(rows):
    out = []
    for anon, d, c, t, reason in rows:
        total = d + c + t
        assert total * 2 == int(total * 2)
        out.append({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                    "total": total, "pass": total >= 4, "reason": reason})
    return out

def main():
    assert not os.path.exists(OUT), "output already exists, refusing to overwrite"
    block_ids = [json.loads(l)["anon_id"] for l in open(BLOCK, encoding="utf-8") if l.strip()]
    expect = []
    written = 0
    with open(OUT, "a", encoding="utf-8") as f:
        for si, seg in enumerate(SEGS):
            rows = emit(seg)
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
            written += len(rows)
            f.flush()
            expect.extend(r["anon_id"] for r in rows)
            cur = sum(1 for _ in open(OUT, encoding="utf-8"))
            assert cur == written, f"segment {si}: file lines {cur} != written {written}"
            print(f"segment {si+1}: +{len(rows)} (cum {written})")
    got = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(got) == len(block_ids) == 122, (len(got), len(block_ids))
    assert [g["anon_id"] for g in got] == block_ids, "anon_id order mismatch with block"
    for g in got:
        assert abs(g["total"] - (g["direction"] + g["claims"] + g["timing"])) < 1e-9
        assert g["pass"] == (g["total"] >= 4)
        for k in ("direction", "claims", "timing"):
            assert 0 <= g[k] <= 2 and (g[k] * 2) == int(g[k] * 2)
    print("OK total lines:", len(got))

if __name__ == "__main__":
    main()
