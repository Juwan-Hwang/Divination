def emit(seg, mode):
    with open(OUT, mode, encoding="utf-8") as f:
        for anon, d, c, t, reason in seg:
            assert d in (0,0.5,1,1.5,2) and c in (0,0.5,1,1.5,2) and t in (0,0.5,1,1.5,2), anon
            total = d + c + t
            row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                   "total": total, "pass": total >= 4, "reason": reason}
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    n = sum(1 for _ in open(OUT, encoding="utf-8"))
    return n

