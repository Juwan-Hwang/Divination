def num(x):
    return int(x) if float(x) == int(x) else x

def main():
    assert not os.path.exists(OUT), "target exists, refusing to overwrite: %s" % OUT
    with open(BLOCK, encoding="utf-8") as f:
        block_ids = [json.loads(l)["anon_id"] for l in f if l.strip()]
    assert len(block_ids) == 122, len(block_ids)
    assert [s[0] for s in SCORES] == block_ids, "anon order mismatch with block"
    assert len(SCORES) == 122, len(SCORES)
    rows = []
    for anon, d, c, t, reason in SCORES:
        for v in (d, c, t):
            assert v in (0, 0.5, 1, 1.5, 2), (anon, v)
        total = d + c + t
        rows.append({"anon_id": anon, "direction": num(d), "claims": num(c),
                     "timing": num(t), "total": num(total), "pass": total >= 4,
                     "reason": reason})
    seg = 21
    written = 0
    with open(OUT, "a", encoding="utf-8") as f:
        for i in range(0, len(rows), seg):
            chunk = rows[i:i + seg]
            for r in chunk:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
            f.flush()
            written += len(chunk)
            with open(OUT, encoding="utf-8") as g:
                n = sum(1 for _ in g)
            assert n == written, (n, written)
    # final self-verification: reread
    with open(OUT, encoding="utf-8") as f:
        back = [json.loads(l) for l in f if l.strip()]
    assert len(back) == len(block_ids) == 122, len(back)
    assert [r["anon_id"] for r in back] == block_ids
    for r in back:
        assert abs(r["direction"] + r["claims"] + r["timing"] - r["total"]) < 1e-9, r
        assert r["pass"] == (r["total"] >= 4), r
    from collections import Counter
    dist = Counter(r["total"] for r in back)
    npass = sum(1 for r in back if r["pass"])
    print("written:", len(back), "pass:", npass, "fail:", len(back) - npass)
    print("total distribution:", dict(sorted(dist.items())))

