FIELDS = {"case_id", "prediction_text", "basis", "confidence", "trigger"}

def T(cm=False, ru=False, di=False, reason=""):
    return {"changed_main": cm, "reserve_used": ru, "disputed": di, "reason": reason}

def emit(rec):
    assert set(rec.keys()) == FIELDS, rec["case_id"]
    assert 0.0 <= rec["confidence"] <= 1.0
    tr = rec["trigger"]
    assert set(tr.keys()) == {"changed_main", "reserve_used", "disputed", "reason"}
    assert all(isinstance(tr[k], bool) for k in ("changed_main", "reserve_used", "disputed"))
    p = OUT / (rec["case_id"] + ".json")
    p.write_text(json.dumps(rec, ensure_ascii=False, indent=1), encoding="utf-8")
    back = json.loads(p.read_text(encoding="utf-8"))
    assert back == rec
    print("wrote", rec["case_id"])

