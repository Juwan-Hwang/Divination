# ---------------- main ----------------
def main():
    assert set(D.keys()) == set(IDS), (set(IDS) - set(D.keys()), set(D.keys()) - set(IDS))
    OUT.mkdir(parents=True, exist_ok=True)
    sizes = {}
    trig_count = [0, 0, 0]
    systems = {}
    for cid in IDS:
        pred, basis, conf, trig = D[cid]
        for line in basis.splitlines():
            if line.startswith('systems_used='):
                for s in line.split('=',1)[1].strip('[]; ').split(','):
                    systems[s.strip()] = systems.get(s.strip(), 0) + 1
        if cid.startswith('LY'):
            if trig[0]: trig_count[0] += 1
            if trig[1]: trig_count[1] += 1
            if trig[2]: trig_count[2] += 1
        obj = {
            "case_id": cid,
            "prediction_text": pred,
            "basis": basis,
            "confidence": conf,
            "trigger": {"changed_main": trig[0], "reserve_used": trig[1], "disputed": trig[2], "reason": trig[3]},
        }
        path = OUT / f"{cid}.json"
        path.write_text(json.dumps(obj, ensure_ascii=False, indent=2) + "\n", encoding='utf-8')
        sizes[cid] = path.stat().st_size
    # readback verification, exact id set only (no glob over others)
    for cid in IDS:
        obj = json.loads((OUT / f"{cid}.json").read_text(encoding='utf-8'))
        assert obj["case_id"] == cid
        assert set(obj.keys()) == {"case_id", "prediction_text", "basis", "confidence", "trigger"}, obj.keys()
        assert set(obj["trigger"].keys()) == {"changed_main", "reserve_used", "disputed", "reason"}
        if not cid.startswith('LY'):
            assert obj["trigger"] == {"changed_main": False, "reserve_used": False, "disputed": False, "reason": ""}
    print("count", len(IDS), "written", len(sizes))
    print("trigger_counts changed_main/reserve_used/disputed:", trig_count)
    print("systems:", systems)
    for cid in IDS:
        print(cid, sizes[cid])

if __name__ == "__main__":
    main()
