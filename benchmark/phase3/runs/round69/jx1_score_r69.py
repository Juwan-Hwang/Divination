ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    in_rows = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    in_anons = [r["anon_id"] for r in in_rows]
    assert len(SCORES) == 122, f"scores={len(SCORES)}"
    assert [s[0] for s in SCORES] == in_anons, "anon order/set mismatch with input block"
    out_lines = []
    for anon, d, c, t, reason in SCORES:
        for v in (d, c, t):
            assert v in ALLOWED, (anon, v)
        total = d + c + t
        rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        out_lines.append(json.dumps(rec, ensure_ascii=False))
    # segmented write: 4 segments, verify tail after each
    seg = 31
    with open(BLOCK, "w", encoding="utf-8") as f:
        for start in range(0, len(out_lines), seg):
            chunk = out_lines[start:start + seg]
            for line in chunk:
                f.write(line + "\n")
            f.flush()
            tail = BLOCK.read_text(encoding="utf-8").splitlines()
            assert tail[-1] == chunk[-1], f"tail verify failed at {start}"
            assert len(tail) == start + len(chunk), f"count verify failed at {start}"
    final = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert [r["anon_id"] for r in final] == in_anons
    for r in final:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    npass = sum(1 for r in final if r["pass"])
    print(f"lines={len(final)} pass={npass} bytes={BLOCK.stat().st_size}")

if __name__ == "__main__":
    main()
