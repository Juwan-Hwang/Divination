ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    with open(BLOCK, encoding="utf-8") as f:
        in_anons = [json.loads(l)["anon_id"] for l in f if l.strip()]
    assert len(SCORES) == len(in_anons), (len(SCORES), len(in_anons))
    assert [s[0] for s in SCORES] == in_anons, "anon order/set mismatch"
    lines = []
    for anon, d, c, t, reason in SCORES:
        for v in (d, c, t):
            assert v in ALLOWED, (anon, v)
        total = d + c + t
        rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        lines.append(json.dumps(rec, ensure_ascii=False))
    # segmented append: write to temp name in same dir then replace? No: overwrite block in chunks
    CH = 31
    with open(BLOCK, "w", encoding="utf-8") as f:
        done = 0
        for i in range(0, len(lines), CH):
            chunk = lines[i:i+CH]
            for ln in chunk:
                f.write(ln + "\n")
            f.flush(); os.fsync(f.fileno())
            done += len(chunk)
            with open(BLOCK, encoding="utf-8") as vf:
                got = [l for l in vf if l.strip()]
            assert len(got) == done, (len(got), done)
            assert json.loads(got[-1])["anon_id"] == json.loads(chunk[-1])["anon_id"]
    npass = sum(1 for s in SCORES if s[1]+s[2]+s[3] >= 4)
    size = os.path.getsize(BLOCK)
    print(f"lines={len(lines)} pass={npass} bytes={size}")

if __name__ == "__main__":
    main()
