def main():
    mapping = json.loads(MAP_FILE.read_text(encoding="utf-8"))
    rows = [json.loads(l) for l in JUDGE_FILE.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows) == 122, len(rows)
    assert len(SCORES) == 122, len(SCORES)
    orig_ids = [r["anon_id"] for r in rows]
    assert orig_ids == [s[0] for s in SCORES], "anon order mismatch"
    out = []
    for anon_id, d, c, t, reason in SCORES:
        case_id = mapping[anon_id]
        pred = json.loads((BASE / "predictions" / f"{case_id}.json").read_text(encoding="utf-8"))
        assert pred["prediction_text"].strip(), case_id
        total = d + c + t
        out.append({
            "anon_id": anon_id,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        })
    JUDGE_FILE.write_text(
        "".join(json.dumps(o, ensure_ascii=False) + "\n" for o in out),
        encoding="utf-8",
    )
    # validation pass
    back = [json.loads(l) for l in JUDGE_FILE.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(back) == 122
    assert [b["anon_id"] for b in back] == orig_ids
    for b in back:
        assert abs(b["total"] - (b["direction"] + b["claims"] + b["timing"])) < 1e-9
        assert b["pass"] == (b["total"] >= 4)
        for k in ("direction", "claims", "timing"):
            v = b[k]
            assert 0 <= v <= 2 and abs(v * 2 - round(v * 2)) < 1e-9
    print("OK lines=122 validated")

if __name__ == "__main__":
    main()
