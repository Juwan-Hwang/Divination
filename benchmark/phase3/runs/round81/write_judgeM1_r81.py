out_path = "/home/hatch/workspace/divination/benchmark/phase3/runs/round81/acceptance/judging/judgeM1.jsonl"
lines = []
for anon_id, d, c, t, reason in rows:
    total = d + c + t
    rec = {"anon_id": anon_id, "direction": d, "claims": c, "timing": t,
           "total": total, "pass": total >= 4, "reason": reason}
    lines.append(json.dumps(rec, ensure_ascii=False))

assert len(lines) == 27, len(lines)
with open(out_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

with open(out_path, encoding="utf-8") as f:
    written = f.read().splitlines()
assert len(written) == 27, len(written)
for ln in written:
    r = json.loads(ln)
    assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
    assert r["pass"] == (r["total"] >= 4)
npass = sum(1 for ln in written if json.loads(ln)["pass"])
print("bytes:", os.path.getsize(out_path), "lines:", len(written), "pass:", npass)
