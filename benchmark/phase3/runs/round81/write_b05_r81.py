def main():
    assert len(DATA) == 20, f"count {len(DATA)}"
    got = sorted(d["case_id"] for d in DATA)
    assert got == sorted(IDS), f"id set mismatch {got}"
    os.makedirs(OUT, exist_ok=True)
    total = 0
    trig = {"changed_main": 0, "reserve_used": 0, "disputed": 0}
    for d in DATA:
        for k in ("case_id", "prediction_text", "basis", "confidence", "trigger"):
            assert k in d, (d.get("case_id"), k)
        assert 0.0 <= d["confidence"] <= 1.0
        if d["case_id"].startswith("DT-"):
            for kk in trig:
                if d["trigger"][kk]:
                    trig[kk] += 1
        else:
            assert d["trigger"] == {"changed_main": False, "reserve_used": False, "disputed": False, "reason": ""}, d["case_id"]
        p = os.path.join(OUT, d["case_id"] + ".json")
        with open(p, "w", encoding="utf-8") as f:
            json.dump(d, f, ensure_ascii=False, indent=1)
            f.write("\n")
    # self-verify each file by exact id (no directory listing/glob)
    for cid in IDS:
        p = os.path.join(OUT, cid + ".json")
        with open(p, encoding="utf-8") as f:
            obj = json.load(f)
        assert obj["case_id"] == cid
        assert obj["basis"].splitlines()[0] != ""
        assert "systems_used" in obj["basis"]
        total += os.path.getsize(p)
    print(json.dumps({"written": len(IDS), "liuyao_trigger_counts": trig, "total_bytes": total}, ensure_ascii=False))

if __name__ == "__main__":
    main()
