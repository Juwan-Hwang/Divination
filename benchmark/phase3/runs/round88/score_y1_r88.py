def main():
    rows = [json.loads(l) for l in INP.open(encoding='utf-8')]
    assert len(rows) == 122, len(rows)
    mp = json.load(MAP.open(encoding='utf-8'))
    assert len(S) == 122, len(S)
    assert [s[0] for s in S] == [r['anon_id'] for r in rows], 'anon order/set mismatch'
    # claims full-text verification presence check: every mapped prediction file must have prediction_text read
    for r in rows:
        cid = mp[r['anon_id']]
        p = json.load((BASE / 'predictions' / f'{cid}.json').open(encoding='utf-8'))
        assert p.get('prediction_text'), cid
    if OUT.exists():
        raise SystemExit('output exists, refusing overwrite')
    seg = 31
    written = 0
    with OUT.open('a', encoding='utf-8') as f:
        for start in range(0, len(S), seg):
            chunk = S[start:start+seg]
            for anon, d, c, t, reason in chunk:
                for v in (d, c, t):
                    assert 0 <= v <= 2 and (v * 2) == int(v * 2), (anon, v)
                total = d + c + t
                rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t, "total": total, "pass": total >= 4, "reason": reason}
                assert list(rec.keys()) == ["anon_id","direction","claims","timing","total","pass","reason"]
                assert rec['total'] == d + c + t and rec['pass'] == (total >= 4)
                f.write(json.dumps(rec, ensure_ascii=False) + '\n')
            f.flush()
            written += len(chunk)
            lines = OUT.read_text(encoding='utf-8').strip().split('\n')
            assert len(lines) == written, (len(lines), written)
            for ln in lines:
                o = json.loads(ln)
                assert o['total'] == o['direction'] + o['claims'] + o['timing']
                assert o['pass'] == (o['total'] >= 4)
    final = [json.loads(l) for l in OUT.open(encoding='utf-8')]
    assert len(final) == 122
    assert {o['anon_id'] for o in final} == {r['anon_id'] for r in rows}
    print('OK', len(final), 'pass', sum(1 for o in final if o['pass']))

