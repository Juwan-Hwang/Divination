def check(rows):
    for r in rows:
        assert set(r.keys()) == {"anon_id","direction","claims","timing","total","pass","reason"}, r
        for k in ("direction","claims","timing"):
            assert 0 <= r[k] <= 2 and abs(r[k]*2 - round(r[k]*2)) < 1e-9, r
        assert abs(r["total"] - (r["direction"]+r["claims"]+r["timing"])) < 1e-9, r
        assert r["pass"] == (r["total"] >= 4), r

def main():
    inp = [json.loads(l) for l in INP.read_text().splitlines() if l.strip()]
    assert len(inp) == 122, len(inp)
    assert len(S) == 122, len(S)
    assert {x[0] for x in S} == {x["anon_id"] for x in inp}
    assert [x[0] for x in S] == [x["anon_id"] for x in inp]
    rows = [{"anon_id":a,"direction":d,"claims":c,"timing":t,
             "total":round(d+c+t,2),"pass":(d+c+t)>=4,"reason":r}
            for a,d,c,t,r in S]
    check(rows)
    if OUT.exists():
        raise SystemExit("output exists, refusing overwrite")
    seg = 31
    written = 0
    for i in range(0, len(rows), seg):
        part = rows[i:i+seg]
        check(part)
        with OUT.open("a") as f:
            for r in part:
                f.write(json.dumps(r, ensure_ascii=False)+"\n")
        written += len(part)
        got = [json.loads(l) for l in OUT.read_text().splitlines() if l.strip()]
        assert len(got) == written, (len(got), written)
        check(got)
        print(f"segment ok cumulative={written}")
    final = [json.loads(l) for l in OUT.read_text().splitlines() if l.strip()]
    assert len(final) == 122 and {r["anon_id"] for r in final} == {x["anon_id"] for x in inp}
    npass = sum(1 for r in final if r["pass"])
    means = {k: round(sum(r[k] for r in final)/len(final),4) for k in ("direction","claims","timing")}
