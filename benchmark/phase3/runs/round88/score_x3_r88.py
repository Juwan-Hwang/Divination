ALLOWED = {0, 0.5, 1, 1.5, 2}
out_lines = []
for anon, d, c, t, reason in S:
    assert d in ALLOWED and c in ALLOWED and t in ALLOWED, anon
    total = d + c + t
    rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
           "total": total, "pass": total >= 4, "reason": reason}
    out_lines.append(json.dumps(rec, ensure_ascii=False))

# segmented append with per-segment assertions
if os.path.exists(OUT):
    raise SystemExit('output already exists, refusing to overwrite')
SEG = 31
written = 0
with open(OUT, 'a', encoding='utf-8') as f:
    for i in range(0, len(out_lines), SEG):
        chunk = out_lines[i:i + SEG]
        for ln in chunk:
            f.write(ln + '\n')
        f.flush()
        written += len(chunk)
        with open(OUT, encoding='utf-8') as g:
            cur = g.read().splitlines()
        assert len(cur) == written, (len(cur), written)
        for ln in cur:
            r = json.loads(ln)
            assert list(r.keys()) == ["anon_id", "direction", "claims", "timing", "total", "pass", "reason"], r
            assert r['direction'] in ALLOWED and r['claims'] in ALLOWED and r['timing'] in ALLOWED
            assert r['total'] == r['direction'] + r['claims'] + r['timing']
