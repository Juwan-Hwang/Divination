def main():
    rows = [json.loads(l) for l in open(INP, encoding='utf-8')]
    mapping = json.load(open(MAP, encoding='utf-8'))
    assert len(rows) == 121, len(rows)
    # host-mapping full-text check: every case prediction_text must be read
    for r in rows:
        cid = mapping[r['anon_id']]
        pj = json.load(open(BASE/'predictions'/f'{cid}.json', encoding='utf-8'))
        assert pj['prediction_text'].strip(), cid
    in_ids = [r['anon_id'] for r in rows]
    assert [d[0] for d in DATA] == in_ids, 'order/set mismatch'
    assert not OUT.exists(), 'output exists, refusing overwrite'
    seg = 31
    written = 0
    with open(OUT, 'w', encoding='utf-8') as f:
        for start in range(0, len(DATA), seg):
            chunk = DATA[start:start+seg]
            for anon, d, c, t, reason in chunk:
                for v in (d, c, t):
                    assert 0 <= v <= 2 and (v*2) == int(v*2), (anon, v)
                total = d + c + t
                rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                f.write(json.dumps(rec, ensure_ascii=False) + '\n')
            f.flush()
            written += len(chunk)
            # per-segment assertion by re-reading
            cur = [json.loads(l) for l in open(OUT, encoding='utf-8')]
            assert len(cur) == written, (len(cur), written)
            for rec in cur:
                assert list(rec.keys()) == ["anon_id","direction","claims","timing","total","pass","reason"], rec
                assert rec['total'] == rec['direction']+rec['claims']+rec['timing']
                assert rec['pass'] == (rec['total'] >= 4)
    final = [json.loads(l) for l in open(OUT, encoding='utf-8')]
    assert len(final) == 121
    assert [r['anon_id'] for r in final] == in_ids
    npass = sum(1 for r in final if r['pass'])
    print('input', len(rows), 'output', len(final), 'pass', npass)
    for k in ('direction','claims','timing'):
        print(k, round(sum(r[k] for r in final)/len(final), 4))

if __name__ == '__main__':
    main()
