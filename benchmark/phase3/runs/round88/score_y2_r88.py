ALLOWED = {0.0, 0.5, 1.0, 1.5, 2.0}
FIELDS = {"anon_id", "direction", "claims", "timing", "total", "pass", "reason"}


def check_row(r):
    assert set(r.keys()) == FIELDS, r
    for k in ("direction", "claims", "timing"):
        assert r[k] in ALLOWED, r
    assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9, r
    assert r["pass"] == (r["total"] >= 4), r
    assert isinstance(r["pass"], bool) and isinstance(r["reason"], str) and r["reason"]


def main():
    rows_in = [json.loads(l) for l in INP.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows_in) == 122, len(rows_in)
    assert len(SCORES) == 122, len(SCORES)
    recs = []
    for d, (di, cl, ti, reason) in zip(rows_in, SCORES):
        total = di + cl + ti
        recs.append({"anon_id": d["anon_id"], "direction": di, "claims": cl,
                     "timing": ti, "total": total, "pass": total >= 4, "reason": reason})
    # segmented append: 5 segments, assert after each
    if OUT.exists():
        raise SystemExit(f"refuse to overwrite existing {OUT}")
    seg = 25
    written = 0
    with OUT.open("a", encoding="utf-8") as f:
        for s in range(0, len(recs), seg):
            chunk = recs[s:s + seg]
            for r in chunk:
                check_row(r)
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
            f.flush()
            written += len(chunk)
            cur = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
            assert len(cur) == written, (len(cur), written)
            for r in cur:
                check_row(r)
            print(f"segment ok: {written}")
    # final validation
    out_lines = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(out_lines) == len(rows_in) == 122
    assert {r["anon_id"] for r in out_lines} == {d["anon_id"] for d in rows_in}
    assert [r["anon_id"] for r in out_lines] == [d["anon_id"] for d in rows_in]
    for r in out_lines:
        check_row(r)
    n_pass = sum(1 for r in out_lines if r["pass"])
    means = {k: round(sum(r[k] for r in out_lines) / len(out_lines), 4)
             for k in ("direction", "claims", "timing")}
    print(json.dumps({"input": len(rows_in), "output": len(out_lines), "pass": n_pass,
                      "means": means, "bytes": OUT.stat().st_size}, ensure_ascii=False))


if __name__ == "__main__":
    main()
