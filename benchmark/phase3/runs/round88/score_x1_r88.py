def main():
    rows_in = [json.loads(l) for l in INP.read_text(encoding='utf-8').splitlines() if l.strip()]
    assert len(rows_in) == 122, len(rows_in)
    assert [r['anon_id'] for r in rows_in] == [d[0] for d in DATA], 'anon order/set mismatch'
    out_rows = []
    for anon, d, c, t, reason in DATA:
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), (anon, v)
        total = d + c + t
        out_rows.append({'anon_id': anon, 'direction': d, 'claims': c, 'timing': t,
                         'total': total, 'pass': total >= 4, 'reason': reason})
    # segmented append: 4 segments
    if OUT.exists():
        OUT.unlink()
    bounds = [(0, 31), (31, 61), (61, 92), (92, 122)]
    written = 0
    for lo, hi in bounds:
        with OUT.open('a', encoding='utf-8') as f:
            for r in out_rows[lo:hi]:
                f.write(json.dumps(r, ensure_ascii=False) + '\n')
        written = hi
        lines = OUT.read_text(encoding='utf-8').splitlines()
        assert len(lines) == written, (len(lines), written)
        for l in lines:
            o = json.loads(l)
            assert list(o.keys()) == ['anon_id', 'direction', 'claims', 'timing', 'total', 'pass', 'reason'], o
            assert o['total'] == o['direction'] + o['claims'] + o['timing']
            assert o['pass'] == (o['total'] >= 4)
    assert len(out_rows) == 122
    npass = sum(1 for r in out_rows if r['pass'])
    print('input', len(rows_in), 'output', len(out_rows), 'pass', npass)
    for k in ('direction', 'claims', 'timing'):
        print(k, round(sum(r[k] for r in out_rows) / len(out_rows), 4))
    print('bytes', OUT.stat().st_size)

if __name__ == '__main__':
    main()
