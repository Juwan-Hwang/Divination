def write_batch(rows, expect_ids, label):
    ids = []
    for cid, trad, ptext, basis, conf, tr in rows:
        rec = {"case_id": cid, "prediction_text": ptext,
               "basis": trad + "\n" + basis,
               "confidence": conf, "trigger": tr}
        with open(os.path.join(OUT, cid + ".json"), "w", encoding="utf-8") as f:
            json.dump(rec, f, ensure_ascii=False, indent=1)
        ids.append(cid)
    assert ids == expect_ids, (label, ids)
    print(label, "written", len(ids))
    return ids

