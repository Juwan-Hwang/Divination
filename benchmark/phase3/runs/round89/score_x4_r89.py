def emit(seg, expected_total):
    lines = []
    for anon, d, c, t, reason in seg:
        total = d + c + t
        lines.append(json.dumps({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                                 "total": total, "pass": total >= 4, "reason": reason}, ensure_ascii=False))
    with open(OUT, 'a') as f:
        for l in lines:
            f.write(l + '\n')
    cur = [json.loads(l) for l in OUT.read_text().splitlines() if l.strip()]
    assert len(cur) == expected_total, (len(cur), expected_total)
    ids = [r['anon_id'] for r in cur]
    assert len(set(ids)) == len(ids)
    print('segment ok, cumulative rows:', len(cur))

