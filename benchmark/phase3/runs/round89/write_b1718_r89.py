def write_seg(preds, expect_ids):
    assert [p["case_id"] for p in preds] == expect_ids, "segment id mismatch"
    for p in preds:
        assert set(p.keys()) == {"case_id", "prediction_text", "basis", "confidence", "trigger"}, p["case_id"]
        assert set(p["trigger"].keys()) == {"changed_main", "reserve_used", "disputed", "reason"}
        path = os.path.join(OUT, p["case_id"] + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(p, f, ensure_ascii=False, indent=1)
    for cid in expect_ids:
        with open(os.path.join(OUT, cid + ".json"), encoding="utf-8") as f:
            d = json.load(f)
        assert d["case_id"] == cid
    print("segment ok:", len(expect_ids), expect_ids[0], "->", expect_ids[-1])

