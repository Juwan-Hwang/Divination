def main():
    block_ids = []
    with open(BLOCK) as f:
        for line in f:
            line = line.strip()
            if line:
                block_ids.append(json.loads(line)['anon_id'])
    assert len(block_ids) == 122, len(block_ids)
    if os.path.exists(OUT):
        os.remove(OUT)
    written = []
    with open(OUT, 'a') as out:
        for si, seg in enumerate(SEGMENTS):
            for (anon, d, c, t, reason) in seg:
                total = d + c + t
                rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                out.write(json.dumps(rec, ensure_ascii=False) + "\n")
                written.append(anon)
            out.flush()
            # per-segment assertion: prefix equality with block order
            assert written == block_ids[:len(written)], f"segment {si} prefix mismatch"
            print(f"segment {si}: cumulative {len(written)} rows OK")
    assert len(written) == 122 and set(written) == set(block_ids)
    npass = 0
    with open(OUT) as f:
        for line in f:
            r = json.loads(line)
            assert abs(r['total'] - (r['direction'] + r['claims'] + r['timing'])) < 1e-9
            assert r['pass'] == (r['total'] >= 4)
            npass += 1 if r['pass'] else 0
    print("TOTAL rows=122 pass=", npass, "bytes=", os.path.getsize(OUT))

if __name__ == '__main__':
    main()
