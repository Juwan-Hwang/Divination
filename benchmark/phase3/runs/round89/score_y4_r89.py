ALL_SEGMENTS = [SEG1, SEG2, SEG3, SEG4]

def write_segment(idx):
    block = load_block()
    seg = ALL_SEGMENTS[idx]
    start = sum(len(s) for s in ALL_SEGMENTS[:idx])
    rows = []
    for j, (d, c, t, reason) in enumerate(seg):
        b = block[start + j]
        total = d + c + t
        rows.append({"anon_id": b["anon_id"], "direction": d, "claims": c, "timing": t,
                     "total": total, "pass": total >= 4, "reason": reason})
    mode = "w" if idx == 0 else "a"
    with open(OUT, mode, encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    done = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(done) == start + len(seg), (len(done), start + len(seg))
    assert [s["anon_id"] for s in done] == [b["anon_id"] for b in block[:start + len(seg)]], "anon order mismatch"
    for s in done:
        assert abs(s["total"] - (s["direction"] + s["claims"] + s["timing"])) < 1e-9, s
        assert s["pass"] == (s["total"] >= 4), s
    print(f"SEG{idx+1} OK cumulative={len(done)} seg_pass={sum(1 for r in rows if r['pass'])}")

