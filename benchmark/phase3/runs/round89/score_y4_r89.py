#!/usr/bin/env python3
"""judgeY block4 R89 scoring helper - dump + segmented write with assertions."""
import json, pathlib, sys
P3 = pathlib.Path("/home/hatch/workspace/divination/benchmark/phase3")
BLOCK = P3/"runs/round89/judging/judgeY-block4.jsonl"
MAP = P3/"runs/round89/judging/host-mapping.json"
OUT = P3/"runs/round89/judging/judgeY-block4-scores.jsonl"

def load_block():
    return [json.loads(l) for l in open(BLOCK, encoding="utf-8") if l.strip()]

def pred_text(anon, mapping):
    cid = mapping[anon]
    d = json.load(open(P3/f"runs/round89/predictions/{cid}.json", encoding="utf-8"))
    return cid, d.get("prediction_text","")

if __name__ == "__main__":
    if sys.argv[1] == "dump":
        lo, hi = int(sys.argv[2]), int(sys.argv[3])
        block = load_block()
        mapping = json.load(open(MAP, encoding="utf-8"))
        for i, b in enumerate(block[lo:hi], start=lo):
            cid, txt = pred_text(b["anon_id"], mapping)
            print(f"=== [{i}] {b['anon_id']} -> {cid}")
            print("PRED:", txt)
            print("OUTCOME:", b.get("outcome_record",""))
            extra = {k: b[k] for k in b if k not in ("anon_id","prediction","outcome_record")}
            if extra:
                print("EXTRA_KEYS:", list(extra.keys()))
            print()
    elif sys.argv[1] == "check":
        block = load_block()
        scores = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
        assert len(scores) == len(block), (len(scores), len(block))
        assert [s["anon_id"] for s in scores] == [b["anon_id"] for b in block], "anon set/order mismatch"
        for s in scores:
            assert abs(s["total"] - (s["direction"]+s["claims"]+s["timing"])) < 1e-9, s
            assert s["pass"] == (s["total"] >= 4), s
            for k in ("direction","claims","timing"):
                assert 0 <= s[k] <= 2 and (s[k]*2) == int(s[k]*2), s
        print(f"CHECK OK rows={len(scores)} pass={sum(1 for s in scores if s['pass'])} bytes={OUT.stat().st_size}")

