def main():
    block = [json.loads(l) for l in BLOCK.read_text(encoding='utf-8').splitlines() if l.strip()]
    assert len(block) == 122, len(block)
    assert len(S) == 122, len(S)
    rows = []
    for o, (d, c, t, r) in zip(block, S):
        total = d + c + t
        rows.append({"anon_id": o["anon_id"], "direction": d, "claims": c, "timing": t,
                     "total": total, "pass": total >= 4, "reason": r})
    segs = [(0, 31), (31, 62), (62, 92), (92, 122)]
    for si, (a, b) in enumerate(segs):
        mode = 'w' if si == 0 else 'a'
        with OUT.open(mode, encoding='utf-8') as f:
            for row in rows[a:b]:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        got = [json.loads(l) for l in OUT.read_text(encoding='utf-8').splitlines() if l.strip()]
        assert len(got) == b, (si, len(got))
        assert [g["anon_id"] for g in got] == [r["anon_id"] for r in rows[:b]], si
        for g in got:
            assert abs(g["total"] - (g["direction"] + g["claims"] + g["timing"])) < 1e-9
            assert g["pass"] == (g["total"] >= 4)
        print(f"segment {si+1} ok: lines={len(got)}")
    print("total lines", len(rows), "pass", sum(1 for r in rows if r["pass"]))

if __name__ == '__main__':
    main()
