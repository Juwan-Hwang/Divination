def main():
    rows = [json.loads(ln) for ln in JUDGE.read_text(encoding='utf-8').splitlines() if ln.strip()]
    mp = json.loads(MAP.read_text(encoding='utf-8'))
    anons = [r['anon_id'] for r in rows]
    assert len(anons) == 122, len(anons)
    cases = [mp[a] for a in anons]
    assert len(set(cases)) == 122
    missing = [c for c in cases if c not in S]
    extra = [k for k in S if k not in set(cases)]
    assert not missing, ('missing', missing)
    assert not extra, ('extra', extra)
    out, npass = [], 0
    for a, c in zip(anons, cases):
        d, cl, t, reason = S[c]
        total = d + cl + t
        ps = total >= 4
        npass += int(ps)
        out.append({'anon_id': a, 'direction': d, 'claims': cl, 'timing': t,
                    'total': total, 'pass': ps, 'reason': reason})
    JUDGE.write_text('\n'.join(json.dumps(o, ensure_ascii=False) for o in out) + '\n', encoding='utf-8')
    back = [json.loads(ln) for ln in JUDGE.read_text(encoding='utf-8').splitlines() if ln.strip()]
    assert len(back) == 122
    assert [b['anon_id'] for b in back] == anons
    for b in back:
        assert abs(b['total'] - (b['direction'] + b['claims'] + b['timing'])) < 1e-9
        assert b['pass'] == (b['total'] >= 4)
    print('written lines:', len(back), 'pass:', npass, 'fail:', 122 - npass)

if __name__ == '__main__':
    main()
