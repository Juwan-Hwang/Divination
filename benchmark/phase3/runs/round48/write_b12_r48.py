# 回读校验
n = 0
cnt = {"changed_main": 0, "reserve_used": 0, "disputed": 0}
for cid in IDS:
    with open(os.path.join(BASE, cid + ".json"), encoding="utf-8") as f:
        o = json.load(f)
    assert o["case_id"] == cid, cid
    for k in ("prediction_text", "basis", "confidence", "trigger"):
        assert k in o and o[k] not in (None, ""), (cid, k)
    assert 0.0 <= o["confidence"] <= 1.0, cid
    for b in ("changed_main", "reserve_used", "disputed"):
        assert isinstance(o["trigger"][b], bool), (cid, b)
        cnt[b] += int(o["trigger"][b])
    assert isinstance(o["trigger"]["reason"], str), cid
    n += 1
assert n == len(IDS) == 20, n
print("WROTE_OK", n)
print("TRIGGER_COUNTS", cnt)
