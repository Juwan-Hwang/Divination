def card(cid, book, loc, tradition, system_label, subject, context, question, setting,
         grade, grade_reason, contam, contam_reason, provenance_note,
         master, statement, outcome_desc, passage, notes=""):
    inp = {
        "id": cid, "tradition": tradition,
        "subject": subject, "context": context, "question": question, "setting": setting,
        "provenance": f"{book}·{loc}；在线全文实取 {provenance_note}；transcription=online-verbatim；访问日期 {DATE}",
        "record_status": "candidate-r48-mining",
        "redistributable": False,
        "license_status": "古典文本公有领域；在线转录站条款未明，内部研究用",
        "notes": notes,
    }
    gold = dict(inp)
    gold["master_predictions"] = [{
        "master": master, "date": None, "tradition": tradition,
        "direction": None, "key_assertions": [],
        "source": f"{book}·{loc}",
        "statement_excerpt": statement,
    }]
    gold["outcome"] = {"description": outcome_desc, "verified_by": "原文结局文本（逐字）"}
    gold["passage_full"] = passage
    gold["grade_suggestion"] = grade
    gold["grade_reason"] = grade_reason
    gold["contamination_suggestion"] = contam
    gold["contamination_reason"] = contam_reason
    return inp, gold

