def main():
    pkg_ids = []
    with open(PKG, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                pkg_ids.append(json.loads(line)["anon_id"])
    row_ids = [r[0] for r in ROWS]
    assert row_ids == pkg_ids, f"order/count mismatch: rows={len(row_ids)} pkg={len(pkg_ids)}"
    out_lines = []
    for anon, d, c, t, reason in ROWS:
        total = d + c + t
        rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        out_lines.append(json.dumps(rec, ensure_ascii=False))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines) + "\n")
    totals = [r[1] + r[2] + r[3] for r in ROWS]
    npass = sum(1 for x in totals if x >= 4)
    print(f"lines={len(out_lines)} pass={npass} mean={sum(totals)/len(totals):.4f}")

if __name__ == "__main__":
    main()
