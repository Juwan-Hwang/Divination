def main():
    packet = json.load(open(os.path.join(JDIR, "packet3.json"), encoding="utf-8"))
    assert len(packet) == 122 and len(S) == 122, (len(packet), len(S))
    out = []
    for row, (d, c, t, reason) in zip(packet, S):
        total = d + c + t
        out.append({"anon_id": row["anon_id"], "direction": d, "claims": c,
                    "timing": t, "total": total, "pass": total >= 4, "reason": reason})
    path = os.path.join(JDIR, "judgeX-block3.jsonl")
    with open(path, "w", encoding="utf-8") as f:
        for o in out:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
    # self-verify
    lines = open(path, encoding="utf-8").read().strip().split("\n")
    assert len(lines) == 122
    parsed = [json.loads(l) for l in lines]
    assert {p["anon_id"] for p in parsed} == {r["anon_id"] for r in packet}
    for p in parsed:
        for k in ("direction", "claims", "timing"):
            assert 0 <= p[k] <= 2 and (p[k] * 2) == int(p[k] * 2), p
        assert p["total"] == p["direction"] + p["claims"] + p["timing"]
        assert p["pass"] == (p["total"] >= 4)
    zeros = sum(1 for p in parsed if p["total"] == 0)
    selfrep = sum(1 for p in parsed if "自报：" in p["reason"])
    print(f"OK rows={len(parsed)} total0={zeros} selfreport={selfrep} pass={sum(1 for p in parsed if p['pass'])}")

if __name__ == "__main__":
    main()
