def main():
    with open(IN_PATH, encoding="utf-8") as f:
        inputs = [json.loads(line) for line in f if line.strip()]
    assert len(inputs) == 122, len(inputs)
    assert len(SCORES) == 122, len(SCORES)
    rows = []
    for inp, (anon, d, c, t, reason) in zip(inputs, SCORES):
        assert inp["anon_id"] == anon, (inp["anon_id"], anon)
        total = d + c + t
        row = {
            "anon_id": anon,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        }
        if anon in FLAGS:
            row["flag"] = FLAGS[anon]
        rows.append(row)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    # 回读自验
    with open(OUT_PATH, encoding="utf-8") as f:
        back = [json.loads(line) for line in f if line.strip()]
    assert len(back) == 122
    assert [r["anon_id"] for r in back] == [r["anon_id"] for r in inputs]
    for r in back:
        assert abs(r["direction"] + r["claims"] + r["timing"] - r["total"]) < 1e-9, r
        assert r["pass"] == (r["total"] >= 4), r
        for k in ("direction", "claims", "timing"):
            assert 0 <= r[k] <= 2 and (r[k] * 2) == int(r[k] * 2), r
    nulls = [r["anon_id"] for r in back if r["total"] is None]
    print(f"OK rows={len(back)} nulls={nulls} flags={[r['anon_id'] for r in back if 'flag' in r]}")
    print(f"pass_count={sum(1 for r in back if r['pass'])} mean_total={sum(r['total'] for r in back)/len(back):.3f}")


if __name__ == "__main__":
    main()
