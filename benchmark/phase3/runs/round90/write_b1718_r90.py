def main():
    with open(BATCHES, encoding="utf-8") as f:
        batches = json.load(f)
    ids = batches["B17"] + batches["B18"]
    assert len(ids) == 40, len(ids)
    assert set(ids) == set(P.keys()), (set(ids) ^ set(P.keys()))
    os.makedirs(OUTDIR, exist_ok=True)
    written = []
    for cid in ids:  # exact list only, no enumeration of OUTDIR
        path = os.path.join(OUTDIR, cid + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(P[cid], f, ensure_ascii=False, indent=1)
        written.append(path)
    # self-verify: re-open each exact output file
    cm = ru = disp = 0
    for cid in ids:
        path = os.path.join(OUTDIR, cid + ".json")
        with open(path, encoding="utf-8") as f:
            d = json.load(f)
        assert d["case_id"] == cid
        for k in ("prediction_text", "basis", "confidence", "trigger"):
            assert k in d, (cid, k)
        assert 0.0 <= d["confidence"] <= 1.0
        t = d["trigger"]
        for k in ("changed_main", "reserve_used", "disputed", "reason"):
            assert k in t, (cid, k)
        if cid.startswith("LY-"):
            cm += bool(t["changed_main"]); ru += bool(t["reserve_used"]); disp += bool(t["disputed"])
        else:
            assert t == {"changed_main": False, "reserve_used": False, "disputed": False, "reason": ""}
        print(cid, os.path.getsize(path))
    print("TOTAL", len(written))
    print("LY_TRIGGER changed_main=%d reserve_used=%d disputed=%d" % (cm, ru, disp))

if __name__ == "__main__":
    main()
