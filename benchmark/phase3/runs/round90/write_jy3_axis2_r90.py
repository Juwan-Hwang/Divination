assert len(rows) == 122, len(rows)
out_lines, nulls, flags = [], [], []
for r in rows:
    aid = r['anon_id']
    if aid not in S:
        out_lines.append(json.dumps({"anon_id": aid, "direction": None, "claims": None, "timing": None, "total": None, "pass": False, "reason": "预测全文不可读/未评分"}, ensure_ascii=False))
        nulls.append(aid); continue
    d, c, t, reason = S[aid]
    total = round(d + c + t, 2)
    rec = {"anon_id": aid, "direction": d, "claims": c, "timing": t, "total": total, "pass": total >= 4, "reason": reason}
    out_lines.append(json.dumps(rec, ensure_ascii=False))
outp.write_text("\n".join(out_lines) + "\n", encoding='utf-8')

# self-verify
back = [json.loads(l) for l in open(outp, encoding='utf-8')]
assert len(back) == 122
assert [b['anon_id'] for b in back] == [r['anon_id'] for r in rows], "order mismatch"
bad = []
for b in back:
    if b['total'] is not None:
        if abs(b['direction'] + b['claims'] + b['timing'] - b['total']) > 1e-9: bad.append(b['anon_id'])
        if b['pass'] != (b['total'] >= 4): bad.append(b['anon_id'] + ':pass')
print(f"lines={len(back)} nulls={nulls} flags={flags}勾稽bad={bad}")
print("pass_count=", sum(1 for b in back if b['pass']))
