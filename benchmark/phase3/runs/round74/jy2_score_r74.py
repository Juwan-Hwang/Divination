def check(rows, orig_anons):
    assert len(rows) == len(orig_anons), (len(rows), len(orig_anons))
    seen = [r['anon_id'] for r in rows]
    assert set(seen) == set(orig_anons)
    for r in rows:
        for k in ('direction', 'claims', 'timing'):
            v = r[k]
            assert 0 <= v <= 2 and abs(v * 2 - round(v * 2)) < 1e-9, (r['anon_id'], k, v)
        assert abs(r['total'] - (r['direction'] + r['claims'] + r['timing'])) < 1e-9
        assert r['pass'] == (r['total'] >= 4)

def main():
    orig = [json.loads(l) for l in BLOCK.read_text(encoding='utf-8').splitlines() if l.strip()]
    orig_anons = [r['anon_id'] for r in orig]
    mapping = json.loads(MAP.read_text(encoding='utf-8'))
    # claims were checked against full prediction_text per case; assert files exist/readable
    for a in orig_anons:
        cid = mapping[a]
        p = json.loads((BASE / 'predictions' / f'{cid}.json').read_text(encoding='utf-8'))
        assert p.get('prediction_text'), cid
        assert a in SCORES, a
    out = []
    for a in orig_anons:
        d, c, t, reason = SCORES[a]
        total = d + c + t
        out.append({'anon_id': a, 'direction': d, 'claims': c, 'timing': t,
                    'total': total, 'pass': total >= 4, 'reason': reason})
    # segmented write: 4 segments, assert after each
    seg = 31
    written = []
    with BLOCK.open('w', encoding='utf-8') as f:
        for i in range(0, len(out), seg):
            chunk = out[i:i + seg]
            for r in chunk:
                f.write(json.dumps(r, ensure_ascii=False) + '\n')
            f.flush()
            written.extend(chunk)
            # per-segment assertions on what is on disk so far
            disk = [json.loads(l) for l in BLOCK.read_text(encoding='utf-8').splitlines() if l.strip()]
            assert len(disk) == len(written)
            assert [r['anon_id'] for r in disk] == [r['anon_id'] for r in written]
            for r in disk:
                for k in ('direction', 'claims', 'timing'):
                    v = r[k]
                    assert 0 <= v <= 2 and abs(v * 2 - round(v * 2)) < 1e-9
                assert abs(r['total'] - (r['direction'] + r['claims'] + r['timing'])) < 1e-9
                assert r['pass'] == (r['total'] >= 4)
    final = [json.loads(l) for l in BLOCK.read_text(encoding='utf-8').splitlines() if l.strip()]
    check(final, orig_anons)
    print('rows', len(final), 'pass', sum(1 for r in final if r['pass']))

if __name__ == '__main__':
    main()
