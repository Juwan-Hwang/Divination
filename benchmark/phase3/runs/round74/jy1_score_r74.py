    orig = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    orig_ids = [r["anon_id"] for r in orig]
    assert len(orig_ids) == 122, len(orig_ids)
    assert set(orig_ids) == set(S.keys()), "anon set mismatch"
    rows = []
    for aid in orig_ids:
        d, c, t, reason = S[aid]
        for v in (d, c, t):
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), (aid, v)
        total = d + c + t
        rows.append({"anon_id": aid, "direction": d, "claims": c, "timing": t,
                     "total": total, "pass": total >= 4, "reason": reason})
    # segmented write: 4 segments, assert after each
    seg = 31
    written = 0
    with BLOCK.open("w", encoding="utf-8") as f:
        for i in range(0, len(rows), seg):
            chunk = rows[i:i + seg]
            for r in chunk:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
            f.flush()
            written += len(chunk)
            got = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
            assert len(got) == written, (len(got), written)
            assert [g["anon_id"] for g in got] == orig_ids[:written]
            for g in got:
                assert g["total"] == g["direction"] + g["claims"] + g["timing"]
                assert g["pass"] == (g["total"] >= 4)
    final = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(final) == 122
    assert {r["anon_id"] for r in final} == set(orig_ids)
    npass = sum(1 for r in final if r["pass"])
    print(f"rows=122 pass={npass}")

