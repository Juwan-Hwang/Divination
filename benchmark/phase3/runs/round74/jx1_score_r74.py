    for anon, d, c, t, reason in seg:
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, anon
        total = d + c + t
        rec = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        seg_lines.append(json.dumps(rec, ensure_ascii=False))
    # per-segment assertions: anon slice matches original block order slice
    start = sum(len(s) for s in SEGMENTS[:si])
    assert [json.loads(l)["anon_id"] for l in seg_lines] == ORIG_ANONS[start:start+len(seg)], si
