def month_state(el, mb):
    me = EL[mb]
    if el == me: return "旺（同月建）"
    if GEN[me] == el: return "相（月建生）"
    if GEN[el] == me: return "休（生月建）"
    if CTL[el] == me: return "囚（克月建）"
    return "死（月建克）"

def rel(a, b):
    """a element acting on b element"""
    if a == b: return "同"
    if GEN[a] == b: return "生"
    if CTL[a] == b: return "克"
    if GEN[b] == a: return "被生"
    return "被克"

def parse_case(cid):
    d = json.loads((INP / f"{cid}.json").read_text(encoding="utf-8"))
    c = d.get("context", {}); a = c.get("attachments", {})
    dg = a.get("date_ganzhi") or c.get("asked_at") or ""
    m = re.search(r"([子丑寅卯辰巳午未申酉戌亥])月.*?([甲乙丙丁戊己庚辛壬癸])([子丑寅卯辰巳午未申酉戌亥])日", dg)
    month = m.group(1) if m else None
    daygz = (m.group(2) + m.group(3)) if m else None
    dayb = m.group(3) if m else None
    kong = a.get("空亡") or ""
    if not kong and m:
        stems = "甲乙丙丁戊己庚辛壬癸"; si = stems.index(m.group(2)); bi = BR.index(m.group(3))
        st = (bi - si) % 12; kong = BR[(st + 10) % 12] + BR[(st + 11) % 12]
    rows = a.get("chart_lines_top_to_bottom", [])[:6]
    lines = []
    for i, row in enumerate(rows):
        pos = 6 - i
        txt = row.replace("孫", "孙").replace("財", "财")
        segs = [s for s in re.split(r"　+", txt) if s.strip()]
        left = segs[0] if segs else txt
        right = segs[-1] if len(segs) > 1 else ""
        mm = re.search(r"(父母|兄弟|子孙|妻财|官鬼)([子丑寅卯辰巳午未申酉戌亥])", left)
        if not mm: continue
        rr = re.search(r"(父母|兄弟|子孙|妻财|官鬼)([子丑寅卯辰巳午未申酉戌亥])", right) if right else None
        lines.append(dict(pos=pos, kin=mm.group(1), br=mm.group(2), el=EL[mm.group(2)],
                          mov=("○" in left or "ㄨ" in left),
                          shi=("世" in left), ying=("应" in left or "應" in left),
                          ch=(rr.group(1) if rr else None), chbr=(rr.group(2) if rr else None),
                          raw=row))
    shi = next((l for l in lines if l["shi"]), None)
    ying = next((l for l in lines if l["ying"]), None)
    return dict(id=cid, q=c.get("question", ""), setting=c.get("setting", ""),
                hex=a.get("hexagram", ""), month=month, daygz=daygz, dayb=dayb,
                kong=kong, lines=lines, shi=shi, ying=ying,
                yong_field=a.get("yongshen", ""), hidden=a.get("hidden_lines", ""),
                nrows=len(a.get("chart_lines_top_to_bottom", [])),
                extra=("复占" in str(list(a.keys()))) or ("復占" in str(list(a.keys()))))

def facts_for(case, yspec):
    """yspec: (kin, br, pos or 0) ; returns fact strings + yong line or None"""
    kin, br, pos = yspec
    cand = [l for l in case["lines"] if l["kin"] == kin and (not br or l["br"] == br) and (not pos or l["pos"] == pos)]
    y = cand[0] if cand else None
    f = []
    mb, db, kong = case["month"], case["dayb"], case["kong"]
    f.append(f"月建{mb}、日辰{case['daygz']}、旬空{kong}")
    if y is None:
        f.append(f"用神{kin}{br or ''}未在現卦六爻直現（取用另據變爻/伏神/日月分流，見下）")
        return f, None
    f.append(f"用神＝{POSN[y['pos']]}爻{y['kin']}{y['br']}{y['el']}{'（世）' if y['shi'] else ''}{'（應）' if y['ying'] else ''}，月令{month_state(y['el'], mb)}")
    if y["br"] in kong: f.append(f"用神{y['br']}臨旬空")
    if BR[(BR.index(mb) + 6) % 12] == y["br"]: f.append("用神月破（月建沖）")
    if db == y["br"]: f.append("用神臨日建")
    if BR[(BR.index(db) + 6) % 12] == y["br"]: f.append("用神逢日沖")
    if mb == y["br"]: f.append("用神臨月建")
    de = EL[db]
    r = rel(de, y["el"])
    if r in ("生", "同"): f.append(f"日辰{db}{de}{'生' if r=='生' else '同'}用神")
    elif r == "克": f.append(f"日辰{db}{de}克用神")
    # 原神/忌神 by element
    yuan = [l for l in case["lines"] if GEN[l["el"]] == y["el"]]
    ji = [l for l in case["lines"] if CTL[l["el"]] == y["el"]]
    def fmt(lst, name):
        if not lst: return f"{name}不上卦"
        s = "、".join(f"{POSN[l['pos']]}爻{l['kin']}{l['br']}{l['el']}{'動' if l['mov'] else '靜'}" for l in lst)
        return f"{name}：{s}"
    f.append(fmt(yuan, "原神（生用神之元素爻）"))
    f.append(fmt(ji, "忌神（克用神之元素爻）"))
    if y["mov"] and y["ch"]:
        che = EL[y["chbr"]]
        f.append(f"用神動化：{y['br']}{y['el']}→{y['chbr']}{che}（化神對本爻{rel(che, y['el'])}）")
    return f, y

