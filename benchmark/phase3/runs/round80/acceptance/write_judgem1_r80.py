def main():
    packet = json.loads(PACKET.read_text(encoding="utf-8"))
    packet_ids = [r["anon_id"] for r in packet]
    assert len(packet_ids) == 27, len(packet_ids)
    lines = []
    for anon_id, d, c, t, reason in ROWS:
        total = d + c + t
        rec = {"anon_id": anon_id, "direction": d, "claims": c, "timing": t,
               "total": total, "pass": total >= 4, "reason": reason}
        lines.append(json.dumps(rec, ensure_ascii=False))
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # 回读断言
    back = [json.loads(x) for x in OUT.read_text(encoding="utf-8").splitlines() if x.strip()]
    assert len(back) == 27, len(back)
    assert {r["anon_id"] for r in back} == set(packet_ids), "anon_id set mismatch"
    for r in back:
        assert set(r.keys()) == {"anon_id", "direction", "claims", "timing", "total", "pass", "reason"}, r
        for k in ("direction", "claims", "timing"):
            v = r[k]
            assert 0 <= v <= 2 and (v * 2) == int(v * 2), (r["anon_id"], k, v)
        assert r["total"] == r["direction"] + r["claims"] + r["timing"], r
        assert r["pass"] == (r["total"] >= 4), r
    n_pass = sum(1 for r in back if r["pass"])
    md = sum(r["direction"] for r in back) / 27
    mc = sum(r["claims"] for r in back) / 27
    mt = sum(r["timing"] for r in back) / 27
    print(f"OK lines=27 pass={n_pass} mean_direction={md:.4f} mean_claims={mc:.4f} mean_timing={mt:.4f}")
    print("assertions: lines=27, anon_id set equal, fields complete, total=sum, pass=(total>=4), scores 0-2 in 0.5 steps — ALL PASSED")

if __name__ == "__main__":
    main()
