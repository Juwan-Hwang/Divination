def main():
    with open(MAP, encoding="utf-8") as f:
        mapping = json.load(f)
    pkg = []
    with open(PKG, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                pkg.append(json.loads(line))
    assert len(pkg) == len(SCORES), f"包条目数 {len(pkg)} 与评分条数 {len(SCORES)} 不等"

    out_rows = []
    for entry, (d, c, t, reason) in zip(pkg, SCORES):
        anon = entry["anon_id"]
        case_id = mapping[anon]
        # 回读 prediction_text 全文（存在性与非空断言；评分已逐条据全文作出）
        with open(f"{BASE}/predictions/{case_id}.json", encoding="utf-8") as f:
            pred = json.load(f)
        assert pred["prediction_text"].strip(), f"{case_id} prediction_text 为空"
        total = d + c + t
        out_rows.append({
            "anon_id": anon,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        })

    with open(OUT, "w", encoding="utf-8") as f:
        for r in out_rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # 写后逐行回读断言
    back = []
    with open(OUT, encoding="utf-8") as f:
        for line in f:
            back.append(json.loads(line))
    assert len(back) == len(pkg), "回读行数与包条目数不等"
    assert {r["anon_id"] for r in back} == {e["anon_id"] for e in pkg}, "anon_id 集合与包不全等"
    allowed = {0, 0.5, 1.0, 1.5, 2.0}
    for r in back:
        assert set(r.keys()) == {"anon_id", "direction", "claims", "timing", "total", "pass", "reason"}, f"字段不齐: {r}"
        for k in ("direction", "claims", "timing"):
            assert r[k] in allowed, f"分值越界或非0.5步进: {r}"
        assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9, f"total 不等于三项和: {r}"
        assert r["pass"] == (r["total"] >= 4), f"pass 定义不符: {r}"
        assert isinstance(r["reason"], str) and r["reason"].strip(), f"reason 为空: {r}"

    n = len(back)
    npass = sum(1 for r in back if r["pass"])
    md = sum(r["direction"] for r in back) / n
    mc = sum(r["claims"] for r in back) / n
    mt = sum(r["timing"] for r in back) / n
    print(f"ASSERTIONS_OK rows={n} pass={npass} mean_direction={md:.4f} mean_claims={mc:.4f} mean_timing={mt:.4f}")


if __name__ == "__main__":
    main()
