def main():
    rows = [json.loads(l) for l in open(PKG, encoding="utf-8") if l.strip()]
    assert len(S) == len(rows), f"分数条数 {len(S)} != 包条目数 {len(rows)}"
    out = []
    for r, (d, c, t, reason) in zip(rows, S):
        total = d + c + t
        out.append({"anon_id": r["anon_id"], "direction": d, "claims": c,
                    "timing": t, "total": total, "pass": total >= 4, "reason": reason})
    with open(OUT, "w", encoding="utf-8") as f:
        for o in out:
            f.write(json.dumps(o, ensure_ascii=False) + "\n")
    # 逐行回读断言
    back = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(back) == len(rows), "回读行数不等于包条目数"
    assert {b["anon_id"] for b in back} == {r["anon_id"] for r in rows}, "anon_id 集合与包不全等"
    for b in back:
        assert set(b) == {"anon_id","direction","claims","timing","total","pass","reason"}, f"字段不齐 {b}"
        for k in ("direction","claims","timing"):
            v = b[k]
            assert 0 <= v <= 2 and abs(v*2 - round(v*2)) < 1e-9, f"分值越界或非0.5步进 {b}"
        assert abs(b["total"] - (b["direction"]+b["claims"]+b["timing"])) < 1e-9, f"total 不符 {b}"
        assert b["pass"] == (b["total"] >= 4), f"pass 不符 {b}"
    n = len(back)
    print(f"OK rows={n} pass={sum(b['pass'] for b in back)}")
    print(f"means direction={sum(b['direction'] for b in back)/n:.4f} claims={sum(b['claims'] for b in back)/n:.4f} timing={sum(b['timing'] for b in back)/n:.4f}")

if __name__ == "__main__":
    main()
