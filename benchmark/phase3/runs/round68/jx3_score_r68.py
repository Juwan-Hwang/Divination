def main():
    with open(BLOCK, encoding="utf-8") as f:
        orig_rows = [json.loads(line) for line in f if line.strip()]
    orig_anons = [r["anon_id"] for r in orig_rows]
    assert len(orig_anons) == 122, f"原块行数异常: {len(orig_anons)}"
    assert set(orig_anons) == set(SCORES.keys()), "评分表 anon 全集与原块不一致"
    assert len(set(orig_anons)) == len(orig_anons), "原块 anon 有重复"

    out = []
    for anon in orig_anons:
        d, c, t, reason = SCORES[anon]
        for v in (d, c, t):
            assert v in ALLOWED, f"{anon} 分值非法: {v}"
        total = d + c + t
        row = {
            "anon_id": anon,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        }
        assert row["total"] == row["direction"] + row["claims"] + row["timing"]
        assert row["pass"] == (row["total"] >= 4)
        out.append(row)

    with open(BLOCK, "w", encoding="utf-8") as f:
        for row in out:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"wrote {len(out)} rows, pass={sum(1 for r in out if r['pass'])}")

if __name__ == "__main__":
    main()
