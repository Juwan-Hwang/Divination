def main():
    orig_lines = [l for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    orig_anons = [json.loads(l)["anon_id"] for l in orig_lines]
    assert len(orig_anons) == 122, len(orig_anons)
    assert set(orig_anons) == set(SCORES), (set(orig_anons) ^ set(SCORES))
    out = []
    for anon in orig_anons:
        d, c, t, reason = SCORES[anon]
        for v in (d, c, t):
            assert v in ALLOWED, (anon, v)
        total = d + c + t
        out.append({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                    "total": total, "pass": total >= 4, "reason": reason})
    for r in out:
        assert r["total"] == r["direction"] + r["claims"] + r["timing"]
        assert r["pass"] == (r["total"] >= 4)
    BLOCK.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in out) + "\n", encoding="utf-8")
    print(f"lines={len(out)} pass={sum(r['pass'] for r in out)} bytes={BLOCK.stat().st_size}")

