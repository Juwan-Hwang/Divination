def main():
    with open(BLOCK, encoding="utf-8") as f:
        orig_lines = [ln for ln in f.read().splitlines() if ln.strip()]
    orig_anons = [json.loads(ln)["anon_id"] for ln in orig_lines]
    orig_set = set(orig_anons)
    assert len(orig_lines) == 121, f"原块行数 {len(orig_lines)} != 121"
    assert len(orig_set) == 121, "原块 anon 有重复"
    assert set(SCORES.keys()) == orig_set, (
        f"评分覆盖与原块 anon 全集不全等: 缺={orig_set - set(SCORES)} 多={set(SCORES) - orig_set}"
    )
    out = []
    for anon in orig_anons:
        d, c, t, reason = SCORES[anon]
        for v in (d, c, t):
            assert v in ALLOWED, f"{anon} 分值 {v} 不在量表集合"
        total = d + c + t
        row = {
            "anon_id": anon,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        }
        assert row["total"] == row["direction"] + row["claims"] + row["timing"]
        assert row["pass"] == (row["total"] >= 4)
        out.append(row)
    assert len(out) == 121
    with open(BLOCK, "w", encoding="utf-8") as f:
        for row in out:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    n_pass = sum(1 for r in out if r["pass"])
    print(f"rows={len(out)} pass={n_pass}")

if __name__ == "__main__":
    main()
