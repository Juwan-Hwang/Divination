def main():
    orig_lines = BLOCK.read_text(encoding="utf-8").splitlines()
    orig_rows = [json.loads(l) for l in orig_lines if l.strip()]
    orig_anons = [r["anon_id"] for r in orig_rows]
    orig_set = set(orig_anons)
    assert len(orig_rows) == 122, f"原块行数异常: {len(orig_rows)}"
    assert set(SCORES.keys()) == orig_set, (
        f"评分键与原块 anon 全集不全等: 缺{orig_set - set(SCORES)} 多{set(SCORES) - orig_set}"
    )
    out = []
    for anon in orig_anons:
        d, c, t, reason = SCORES[anon]
        for v in (d, c, t):
            assert v in ALLOWED, f"{anon} 分值越界: {v}"
        total = d + c + t
        row = {
            "anon_id": anon,
            "direction": d,
            "claims": c,
            "timing": t,
            "total": total,
            "pass": total >= 4,
            "reason": reason,
        }
        assert row["total"] == row["direction"] + row["claims"] + row["timing"]
        assert row["pass"] == (row["total"] >= 4)
        out.append(row)
    text = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in out)
    BLOCK.write_text(text, encoding="utf-8")
    # 覆写后回读全等断言
    new_rows = [json.loads(l) for l in BLOCK.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert [r["anon_id"] for r in new_rows] == orig_anons, "覆写后 anon 序列与原块不一致"
    npass = sum(1 for r in new_rows if r["pass"])
    nbytes = BLOCK.stat().st_size
    print(f"lines={len(new_rows)} pass={npass} bytes={nbytes}")

if __name__ == "__main__":
    main()
