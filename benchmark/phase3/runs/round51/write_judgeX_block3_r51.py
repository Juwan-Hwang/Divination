    lines = []
    for anon, d, c, t, reason in SCORES:
        assert d in allowed and c in allowed and t in allowed, anon
        total = d + c + t
        lines.append(json.dumps({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                                 "total": total, "pass": total >= 4, "reason": reason},
                                ensure_ascii=False))
    BLOCK.write_text("\n".join(lines) + "\n", encoding="utf-8")
