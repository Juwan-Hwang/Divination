ALLOWED = {0, 0.5, 1, 1.5, 2}

def main():
    rows_in = [json.loads(l) for l in IN_PATH.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows_in) == 121, len(rows_in)
    assert len(SCORES) == 121, len(SCORES)
    in_anons = [r["anon_id"] for r in rows_in]
    out = []
    for anon, d, c, t, reason in SCORES:
        assert d in ALLOWED and c in ALLOWED and t in ALLOWED, anon
        total = d + c + t
        out.append({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                    "total": total, "pass": total >= 4, "reason": reason})
    assert len(out) == len(rows_in)
    assert {o["anon_id"] for o in out} == set(in_anons)
    assert [o["anon_id"] for o in out] == in_anons, "order/anon mismatch with input"
    for o in out:
        assert o["total"] == o["direction"] + o["claims"] + o["timing"]
        assert o["pass"] == (o["total"] >= 4)
    OUT_PATH.write_text("\n".join(json.dumps(o, ensure_ascii=False) for o in out) + "\n", encoding="utf-8")
    # re-read self-verify
    back = [json.loads(l) for l in OUT_PATH.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(back) == 121
    assert {b["anon_id"] for b in back} == set(in_anons)
    for b in back:
        assert b["total"] == b["direction"] + b["claims"] + b["timing"]
        assert b["pass"] == (b["total"] >= 4)
        assert b["direction"] in ALLOWED and b["claims"] in ALLOWED and b["timing"] in ALLOWED
    mean = sum(b["total"] for b in back) / len(back)
    print(f"wrote {len(back)} rows; mean total = {mean:.4f}; passes = {sum(b['pass'] for b in back)}")

if __name__ == "__main__":
    main()
