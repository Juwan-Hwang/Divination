def main():
    raw = INPUT.read_text(encoding="utf-8").splitlines()
    # If file already contains scored rows (re-run), anon ids are still the first field; support both shapes.
    in_rows = [json.loads(l) for l in raw if l.strip()]
    in_anons = [r["anon_id"] for r in in_rows]
    assert len(in_rows) == 122, f"input rows {len(in_rows)} != 122"
    allowed = {0, 0.5, 1, 1.5, 2}
    out = []
    for anon, d, c, t, reason in SCORES:
        assert d in allowed and c in allowed and t in allowed, anon
        total = d + c + t
        out.append({"anon_id": anon, "direction": d, "claims": c, "timing": t,
                    "total": total, "pass": total >= 4, "reason": reason})
    assert len(out) == len(in_rows), "output rows != input rows"
    assert {o["anon_id"] for o in out} == set(in_anons), "anon set mismatch"
    assert [o["anon_id"] for o in out] == in_anons, "anon order mismatch"
    for o in out:
        assert o["total"] == o["direction"] + o["claims"] + o["timing"]
        assert o["pass"] == (o["total"] >= 4)
    INPUT.write_text("\n".join(json.dumps(o, ensure_ascii=False) for o in out) + "\n", encoding="utf-8")
    # re-read self-verify
    chk = [json.loads(l) for l in INPUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(chk) == 122 and [c["anon_id"] for c in chk] == in_anons
    for c in chk:
        assert c["total"] == c["direction"] + c["claims"] + c["timing"]
        assert c["pass"] == (c["total"] >= 4)
        assert c["direction"] in allowed and c["claims"] in allowed and c["timing"] in allowed
    mean = sum(c["total"] for c in chk) / len(chk)
    print(f"wrote {len(chk)} rows; mean total = {mean:.4f}")

if __name__ == "__main__":
    main()
