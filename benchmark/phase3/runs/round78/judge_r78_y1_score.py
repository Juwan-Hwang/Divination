def main():
    rows = [json.loads(l) for l in PKG.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(rows) == 122, len(rows)
    assert len(SCORES) == len(rows), (len(SCORES), len(rows))
    if OUT.exists():
        raise SystemExit("output already exists, refusing to overwrite")
    recs = []
    for r, (d, c, t, reason) in zip(rows, SCORES):
        total = d + c + t
        recs.append({"anon_id": r["anon_id"], "direction": d, "claims": c, "timing": t,
                     "total": total, "pass": total >= 4, "reason": reason})
    # segmented append: ~30 per segment, anon-set assertion after each
    bounds = [(0, 31), (31, 62), (62, 92), (92, 122)]
    written = []
    for a, b in bounds:
        with OUT.open("a", encoding="utf-8") as f:
            for rec in recs[a:b]:
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
        written += recs[a:b]
        cur = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
        assert len(cur) == len(written), (len(cur), len(written))
        assert {x["anon_id"] for x in cur} == {x["anon_id"] for x in written}
        assert [x["anon_id"] for x in cur] == [x["anon_id"] for x in written]
        print(f"segment {a}-{b}: ok, cumulative {len(cur)}")
    final = [json.loads(l) for l in OUT.read_text(encoding="utf-8").splitlines() if l.strip()]
    assert len(final) == len(rows) == 122
    assert {x["anon_id"] for x in final} == {r["anon_id"] for r in rows}
    for x in final:
        assert abs(x["total"] - (x["direction"] + x["claims"] + x["timing"])) < 1e-9
        assert x["pass"] == (x["total"] >= 4)
        for k in ("direction", "claims", "timing"):
            assert x[k] * 2 == int(x[k] * 2) and 0 <= x[k] <= 2
    print("TOTAL", len(final), "PASS", sum(1 for x in final if x["pass"]))

if __name__ == "__main__":
    main()
