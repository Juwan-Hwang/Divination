def tradition_line(cid):
    d = json.loads((BASE/f"inputs-dev12/{cid}.json").read_text())
    if "tradition" in d and d["tradition"]:
        _m = {"liuyao":"liuyao","六爻":"liuyao","meihua":"meihua"}
        return f"tradition: {d['tradition']}（卡面逐字照錄）", _m.get(d["tradition"], d["tradition"])
    if "system" in d and d["system"]:
        return f"system: {d['system']}（卡面逐字照錄）", d["system"]
    return "卡面未標註 tradition 字段，按題面體裁自決", None

