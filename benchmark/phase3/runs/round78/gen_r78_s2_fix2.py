import json
BASE="/home/hatch/workspace/divination/benchmark/phase3/runs/round78/predictions"
def patch(cid, pairs):
    p=f"{BASE}/{cid}.json"
    d=json.load(open(p,encoding="utf-8"))
    for a,b in pairs:
        assert a in d["prediction_text"], (cid,a[:20])
        d["prediction_text"]=d["prediction_text"].replace(a,b)
    json.dump(d,open(p,"w",encoding="utf-8"),ensure_ascii=False,indent=1)
    print("patched",cid)

