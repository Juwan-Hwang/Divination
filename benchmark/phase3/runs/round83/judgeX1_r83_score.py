    assert not missing, f"missing scores: {missing}"
    extra = [a for a in S if a not in anons]
    assert not extra, f"extra scores: {extra}"
    if os.path.exists(OUT):
        os.remove(OUT)
    # segmented append: 3 batches, assert after each
    batches = [anons[i::3] for i in range(3)]  # placeholder, replaced below
    # use contiguous segments instead
    n = len(anons)
    segs = [anons[: n // 3], anons[n // 3 : 2 * n // 3], anons[2 * n // 3 :]]
    written = 0
    with open(OUT, "a", encoding="utf-8") as f:
        for seg in segs:
            for a in seg:
                d, c, t, reason = S[a]
                total = d + c + t
                rec = {"anon_id": a, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                f.write(json.dumps(rec, ensure_ascii=False) + "\n")
            f.flush()
            written += len(seg)
