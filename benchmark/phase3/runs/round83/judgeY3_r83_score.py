def main():
    src = [json.loads(l) for l in open(SRC, encoding="utf-8") if l.strip()]
    assert len(src) == len(S), (len(src), len(S))
    assert [r["anon_id"] for r in src] == [s[0] for s in S], "anon order mismatch"
    open(OUT, "w", encoding="utf-8").close()
    batch = 31
    written = 0
    for start in range(0, len(S), batch):
        chunk = S[start:start + batch]
        with open(OUT, "a", encoding="utf-8") as f:
            for anon, d, c, t, reason in chunk:
                assert d in [i * 0.5 for i in range(5)] and c in [i * 0.5 for i in range(5)] and t in [i * 0.5 for i in range(5)]
                total = d + c + t
                row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        written += len(chunk)
        got = sum(1 for _ in open(OUT, encoding="utf-8"))
        assert got == written, (got, written)
        print(f"batch ok: {written}")
    # final self-verify
    rows = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert len(rows) == len(S)
    for r, s in zip(rows, S):
        assert r["anon_id"] == s[0]
        assert set(r) == {"anon_id", "direction", "claims", "timing", "total", "pass", "reason"}
        assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
        assert r["pass"] == (r["total"] >= 4)
    print("rows", len(rows), "pass", sum(1 for r in rows if r["pass"]))

if __name__ == "__main__":
    main()
