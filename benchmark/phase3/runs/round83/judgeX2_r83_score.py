def main():
    src_ids = [json.loads(l)["anon_id"] for l in open(SRC, encoding="utf-8") if l.strip()]
    assert [s[0] for s in S] == src_ids, "anon order mismatch vs block2"
    assert len(S) == len(src_ids)
    if os.path.exists(OUT):
        os.remove(OUT)
    B = 31
    for i in range(0, len(S), B):
        batch = S[i:i+B]
        with open(OUT, "a", encoding="utf-8") as f:
            for anon, d, c, t, reason in batch:
                total = d + c + t
                row = {"anon_id": anon, "direction": d, "claims": c, "timing": t,
                       "total": total, "pass": total >= 4, "reason": reason}
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
        rows = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
        assert len(rows) == i + len(batch), f"count after batch {i}"
        for r in rows:
            assert abs(r["total"] - (r["direction"] + r["claims"] + r["timing"])) < 1e-9
            assert r["pass"] == (r["total"] >= 4)
            assert set(r) == {"anon_id","direction","claims","timing","total","pass","reason"}
        print(f"batch@{i}: cumulative {len(rows)} OK")
    rows = [json.loads(l) for l in open(OUT, encoding="utf-8") if l.strip()]
    assert [r["anon_id"] for r in rows] == src_ids
    npass = sum(1 for r in rows if r["pass"])
    print(f"FINAL rows={len(rows)} pass={npass} bytes={os.path.getsize(OUT)}")

